#include <errno.h>
#include <stddef.h>
#include <stdint.h>

#include "cplus_safecrt_upstream.h"

/* ---------------------------------------------------------------------
 * Local stand-ins for safeclib internals.
 *
 * The error numbers below are copied verbatim from
 * third_party/safeclib/include/safe_lib_errno.h at the pinned commit.
 * RSIZE_MAX_MEM matches the value generated by scripts/build_safecrt.sh
 * (RSIZE_MAX_STR = 4UL << 10, RSIZE_MAX_MEM = RSIZE_MAX_STR * 4).
 *
 * Adaptation: upstream's invoke_safe_mem_constraint_handler /
 * invoke_safe_str_constraint_handler calls are replaced by the local no-op
 * below, because this TU must not depend on the safeclib archive. errno is
 * still set at exactly the same call sites as in upstream bsearch_s.
 * The __builtin_object_size-based BOS/basebos/destbos branches are omitted;
 * the public entry points here have no object-size parameter. The core
 * search/scan algorithms and the constraint ordering are preserved.
 * --------------------------------------------------------------------- */
static void cplus_sc_upstream_constraint(const char *msg, void *ptr, int code)
{
    (void)msg;
    (void)ptr;
    (void)code;
}

#define CPLUS_SC_UPSTREAM_BND_CHK_PTR_BOUNDS(p, n) ((void)0)

/* bsearch_s -- third_party/safeclib/src/misc/bsearch_s.c
 *
 * C11 K.3.6.3.1. Upstream body _bsearch_s_chk(); the binary-search loop is
 * kept verbatim. Adaptations: renamed symbol; 6-argument public signature
 * (no trailing basebos); BOS object-size branch and BND_CHK_PTR_BOUNDS
 * guarded out; constraint handler replaced as described above. */
void *cplus_sc_upstream_bsearch_s(const void *key, const void *base,
                                  size_t nmemb, size_t size,
                                  int (*compar)(const void *k, const void *y,
                                                void *context),
                                  void *context)
{
    if (nmemb != 0) {
        if (key == NULL || base == NULL || compar == NULL) {
            cplus_sc_upstream_constraint(
                "bsearch_s: key/base/compar is null", (void *)base,
                CPLUS_SC_UPSTREAM_ESNULLP);
            errno = CPLUS_SC_UPSTREAM_ESNULLP;
            return NULL;
        }
    }
    if (nmemb > CPLUS_SC_UPSTREAM_RSIZE_MAX_MEM ||
        size > CPLUS_SC_UPSTREAM_RSIZE_MAX_MEM) {
        cplus_sc_upstream_constraint("bsearch_s: nmemb or size exceeds max",
                                     (void *)base,
                                     CPLUS_SC_UPSTREAM_ESLEMAX);
        errno = CPLUS_SC_UPSTREAM_ESLEMAX;
        return NULL;
    }
    CPLUS_SC_UPSTREAM_BND_CHK_PTR_BOUNDS(base, nmemb * size);

    errno = 0;

    while (nmemb > 0) {
        void *ptry = (char *)base + size * (nmemb / 2);
        int sign = compar(key, ptry, context);
        if (!sign)
            return ptry;
        else if (nmemb == 1)
            break;
        else if (sign < 0) {
            nmemb /= 2;
        } else {
            base = ptry;
            nmemb -= nmemb / 2;
        }
    }
    return NULL;
}

/* memrchr_s -- third_party/safeclib/src/extmem/memrchr_s.c
 *
 * safeclib extension. Upstream body _memrchr_s_chk() delegating to
 * _memrchr_s_uchk(); the #else (HAVE_MEMRCHR undefined) portable fallback
 * loop is copied verbatim so this TU needs no platform memrchr() and no
 * safeclib symbols. Adaptations: renamed symbol; 4-argument public
 * signature (no destbos); BOS branch and bound macro guarded out;
 * constraint handler replaced as described above. */
int cplus_sc_upstream_memrchr_s(const void *dest, size_t dmax, int ch,
                                void **resultp)
{
    if (resultp == NULL) {
        cplus_sc_upstream_constraint("memrchr_s: resultp is null", NULL,
                                     CPLUS_SC_UPSTREAM_ESNULLP);
        return CPLUS_SC_UPSTREAM_ESNULLP;
    }
    *resultp = NULL;

    if (dest == NULL) {
        cplus_sc_upstream_constraint("memrchr_s: dest is null", (void *)dest,
                                     CPLUS_SC_UPSTREAM_ESNULLP);
        return CPLUS_SC_UPSTREAM_ESNULLP;
    }
    if (dmax == 0) {
        cplus_sc_upstream_constraint("memrchr_s: dmax is 0", (void *)dest,
                                     CPLUS_SC_UPSTREAM_ESZEROL);
        return CPLUS_SC_UPSTREAM_ESZEROL;
    }
    if (dmax > CPLUS_SC_UPSTREAM_RSIZE_MAX_MEM) {
        cplus_sc_upstream_constraint("memrchr_s: dmax exceeds max",
                                     (void *)dest, CPLUS_SC_UPSTREAM_ESLEMAX);
        return CPLUS_SC_UPSTREAM_ESLEMAX;
    }
    CPLUS_SC_UPSTREAM_BND_CHK_PTR_BOUNDS(dest, dmax);
    if (ch > 255) {
        cplus_sc_upstream_constraint("memrchr_s: ch exceeds max", NULL,
                                     CPLUS_SC_UPSTREAM_ESLEMAX);
        return CPLUS_SC_UPSTREAM_ESLEMAX;
    }

    /* Verbatim upstream _memrchr_s_uchk() portable fallback loop. */
    {
        const uint8_t *s = (const uint8_t *)dest;
        uint8_t u8 = (uint8_t)ch;
        while (dmax--) {
            if (s[dmax] == u8) {
                *resultp = (void *)&s[dmax];
                return CPLUS_SC_UPSTREAM_EOK;
            }
        }
    }
    return CPLUS_SC_UPSTREAM_ESNOTFND;
}
