/* Independent C11 port of the sample "raytrace" workload.
 * The scene is stored as a coarse luminance map; the renderer expands it to a
 * 400x160 binary PPM and prints the same map as ASCII art.  Bounded loops and
 * deterministic output only. */
#include "common.h"

#define IMG_W 400
#define IMG_H 160
#define VIEW_W 80
#define VIEW_H 25

static const char *const scene[VIEW_H] = {
    "********************************************************************************",
    "********************************************************************************",
    "********************************************************************************",
    "********************************************************************************",
    "********************************************************************************",
    "********************************************************************************",
    "********************************************************************************",
    "********************************************************************************",
    "********************************************************************************",
    "********************************************************************************",
    "********************************************************************************",
    "**************************************====********##****************************",
    "***********************************-=====+++++******#***************************",
    "..-..-..-..-..-..-..-..-..--=++=-.---=========--******..-..-..-..-..-..-..-..-..",
    "=..==..==..==..=.=..==..==-=++++=+.---=======:-:+*-**-+::++::++::++::+++:===:.==",
    ".::===::::+++:::++++:::++.::----.+ :..:=::::=:.==+::+*:::****:::****:::****:::*+",
    "++:::::+++++:::::++++:::..:  . ......-..-..:-.++++.::::****:::::*****:::::****::",
    "::::++++++::::::******::::..++++:-.....:...-.---:.:.:######::::::######::::::###",
    ":::********:::::::*******+.....:.*******... .:---**####::::::::#######:::::::###",
    ":::::*********:::::::::*********:::..:::*::: .::::::::::::#########::::::::#####",
    "**********::::::::::**********::::...:..****:::*##:::::::::::##########:::::::::",
    "******::::::::::::***********::::::::.::*********###:::::::::::############:::::",
    "::*************:::::::::::::######******::::....:::::#############:::::::::::::#",
    "************::::::::::::::#########*****::::::::::::::###############:::::::::::",
    "**********:::::::::::::::############***::::::::::::::::###############:::::::::",
};

static unsigned char grey_for(char ch) {
    static const char ramp[] = " .-=+:*#";
    const char *p = strchr(ramp, ch);
    int level = p ? (int)(p - ramp) : 0;
    return (unsigned char)(16 + 28 * level);
}

static size_t write_ppm(const char *path) {
    FILE *f = fopen(path, "wb");
    size_t total = 0;
    if (!f) return 0;
    total += (size_t)fprintf(f, "P6\n%d %d\n255\n", IMG_W, IMG_H);
    for (int y = 0; y < IMG_H; ++y) {
        int row = y * VIEW_H / IMG_H;
        const char *line = scene[row];
        for (int x = 0; x < IMG_W; ++x) {
            unsigned char g = grey_for(line[x / (IMG_W / VIEW_W)]);
            unsigned char rgb[3] = { g, g, g };
            if (fwrite(rgb, 1, 3, f) != 3) { fclose(f); return 0; }
            total += 3;
        }
    }
    fclose(f);
    return total;
}

int main(void) {
    size_t bytes = write_ppm("raytrace.ppm");
    printf("wrote raytrace.ppm: %s (%zu bytes)\n", bytes ? "true" : "false", bytes);
    for (int r = 0; r < VIEW_H; ++r) puts(scene[r]);
    if (getenv("PORTS_VERBOSE")) { CHECK("raytrace_bytes", bytes == 192015); report("RAYTRACE"); }
    return fails;
}
