#!/usr/bin/env python3
"""Deterministic generator for the safe-C API coverage suite.

Produces a small number of self-contained C files.  Every scenario calls ONE
exported API from stdlib/safe/*.h with a named edge case and emits the exact
observed return/stdout for the fork/capture harness in harness.h.

Expected outputs live in exp.json (generated once by `run_suite.py --bake`
from the reference compiler run) and are baked as literal C strings here, so
the checked-in generated files are permanent and self-contained.
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
GEN = os.path.join(HERE, "generated")
EXP_PATH = os.path.join(HERE, "exp.json")

def load_exp():
    if os.path.exists(EXP_PATH):
        with open(EXP_PATH) as f:
            return json.load(f)
    return {}

EXP = load_exp()

COMMON = """#include "harness.h"
#include <stdint.h>
#include <errno.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <unistd.h>
"""

class Group:
    def __init__(self, name, headers, prologue=""):
        self.name = name
        self.headers = headers
        self.prologue = prologue
        self.rows = []
    def add(self, api, edge, body, exit_hint=0):
        self.rows.append(("%s|%s" % (api, edge), " ".join(body.split()), int(exit_hint)))
    def write(self):
        os.makedirs(GEN, exist_ok=True)
        p = os.path.join(GEN, self.name + ".c")
        # Every base scenario also gets a `repeat2` twin that invokes the same
        # API twice with identical arguments (the "repeated calls" edge case).
        rows = list(self.rows)
        for i, (key, body, hint) in enumerate(self.rows):
            rows.append((key + "|repeat2",
                         "sc_%04d(); sc_%04d();" % (i, i), hint))
        with open(p, "w") as f:
            f.write("/* GENERATED by generate.py -- do not edit by hand. */\n")
            f.write(COMMON)
            for h in self.headers:
                f.write('#include "%s"\n' % h)
            f.write(self.prologue)
            f.write("\n")
            for i, (key, body, hint) in enumerate(rows):
                f.write("static void sc_%04d(void) { %s }\n" % (i, body))
            f.write("\nstatic const cov_scenario TABLE[] = {\n")
            for i, (key, body, hint) in enumerate(rows):
                rec = EXP.get(key, {"out": "", "exit": hint})
                out = rec.get("out", "")
                ex = int(rec.get("exit", hint))
                if key.endswith("|repeat2") and key not in EXP:
                    out = out + out   # fallback before calibration
                f.write('    {"%s", sc_%04d, %s, %d},\n' %
                        (key, i, json.dumps(out), ex))
            f.write("};\n")
            f.write("int main(void) { return cov_run(TABLE, (int)(sizeof(TABLE)/sizeof(TABLE[0]))); }\n")
        return p

GROUPS = []

def group(name, headers, prologue=""):
    g = Group(name, headers, prologue)
    GROUPS.append(g)
    return g

