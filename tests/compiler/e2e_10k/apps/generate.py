#!/usr/bin/env python3
"""Deterministic generator for the e2e_10k/apps end-to-end suite.

A small number of self-contained C files carry named scenario tables.  Each
scenario forks into a child (see harness.h), emits exact stdout/stderr and an
exact exit code, and is checked by the runner against a frozen reference and
against /usr/bin/clang -std=c11 -O2 differentially.

Sources of scenarios:
  * all 741 proven safe-C API edge bodies from base_scenarios.py, amplified by
    call-count variants (x1/x2/x3/x4/x6/x8) and by systematic parameter
    scaling variants (p2/p3);
  * deterministic app/game patterns (tic-tac-toe, 2048, snake, calculator,
    line editor, hash, pthread, file, JSON) driven by explicit seeds.

No expected values are invented here: tables carry empty expectations until
`run_suite.py --bake` measures the reference compiler twice and freezes them.
"""
import importlib.util
import json
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
GEN = os.path.join(HERE, "generated")
EXP_PATH = os.path.join(HERE, "exp.json")
BASE = os.path.join(HERE, "base_scenarios.py")

COMMON = """#include "harness.h"
#include <stdint.h>
#include <errno.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <unistd.h>
"""

CALL_COUNTS = [1, 2, 3, 4, 6, 8]
SCALES = [2, 3]


def load_exp():
    if os.path.isfile(EXP_PATH):
        with open(EXP_PATH) as f:
            return json.load(f)
    return {}


EXP = load_exp()


def load_base_groups():
    spec = importlib.util.spec_from_file_location("e2e_base_scenarios", BASE)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod.GROUPS


def scale_body(body, factor):
    """Scale every decimal integer literal outside quotes by factor."""
    out = []
    i = 0
    n = len(body)
    while i < n:
        c = body[i]
        if c in ('"', "'"):
            q = c
            lit = [c]
            i += 1
            while i < n:
                if body[i] == '\\' and i + 1 < n:
                    lit.append(body[i]); lit.append(body[i + 1])
                    i += 2
                    continue
                if body[i] == q:
                    if q == '"':
                        # Scaling a copy length must never read past a literal:
                        # pad its object with deterministic NUL bytes.
                        lit.append("\\0" * 512)
                    lit.append(q)
                    i += 1
                    break
                lit.append(body[i])
                i += 1
            out.extend(lit)
            continue
        if c.isdigit():
            j = i
            while j < n and body[j].isdigit():
                j += 1
            prev = body[i - 1] if i else ''
            nxt = body[j] if j < n else ''
            tok = body[i:j]
            if (not prev.isalnum() and prev != '_' and
                    not nxt.isalnum() and nxt != '_' and int(tok) <= 100000):
                v = int(tok)
                if v == 0:
                    out.append(tok)
                else:
                    out.append(str(v * factor))
            else:
                out.append(tok)
            i = j
            continue
        out.append(c)
        i += 1
    return "".join(out)


class FileBuilder:
    def __init__(self, name, headers, prologue=""):
        self.name = name
        self.headers = headers
        self.prologue = prologue
        self.rows = []          # (name, body)
        self.categories = set()

    def add(self, name, body, category):
        self.rows.append((name, " ".join(body.split())))
        self.categories.add(category)

    def write(self):
        os.makedirs(GEN, exist_ok=True)
        path = os.path.join(GEN, self.name + ".c")
        with open(path, "w") as f:
            f.write("/* GENERATED by generate.py -- do not edit. */\n")
            f.write("#define E2E_TABLE_SIZE %d\n" % len(self.rows))
            f.write(COMMON)
            for h in self.headers:
                f.write('#include "%s"\n' % h)
            f.write(self.prologue + "\n")
            for i, (_, body) in enumerate(self.rows):
                f.write("static void sc_%04d(void) { %s }\n" % (i, body))
            f.write("\nstatic const e2e_scenario TABLE[] = {\n")
            for i, (name, _) in enumerate(self.rows):
                rec = EXP.get(name, {})
                out = rec.get("out", "")
                err = rec.get("err", "")
                ex = int(rec.get("exit", 0))
                f.write('    {"%s", sc_%04d, %s, %s, %d},\n' %
                        (name, i, json.dumps(out), json.dumps(err), ex))
            f.write("};\n")
            f.write("int main(void) { return e2e_run(TABLE); }\n")
        return path


STRICT_COMMON = """#include "strict_emit.h"
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include "safe_c.h"
#include "safe_format.h"
#include "safe_memory.h"
#include "safe_string.h"
"""

STRICT_PROLOGUE = """
static unsigned int g_seed;
static char g_text[64];
static char g_copy[64];
static int g_vals[16];
static unsigned int g_rnd(void) {
    g_seed ^= g_seed << 13; g_seed ^= g_seed >> 17; g_seed ^= g_seed << 5;
    return g_seed;
}
static void g_init(unsigned int s) {
    g_seed = s + 1u;
    (void)memset_s(g_text, sizeof(g_text), 0, sizeof(g_text));
    (void)memset_s(g_copy, sizeof(g_copy), 0, sizeof(g_copy));
    (void)memset_s(g_vals, sizeof(g_vals), 0, sizeof(g_vals));
}
"""


def strict_file():
    rows = []
    for seed in range(1, 201):
        k = seed % 5
        if k == 0:
            body = ('long long a,b,c; g_init(%du); a=(long long)(g_rnd()%%1000); '
                    'b=(long long)(g_rnd()%%1000); c=(long long)((g_rnd()%%97)+1); '
                    'E(A,a); E(B,b); E(C,c);' % seed)
        elif k == 1:
            body = ('int x,y; g_init(%du); x=(int)(g_rnd()%%100); '
                    'y=(int)(g_rnd()%%100); '
                    '(void)snprintf_s(g_text,sizeof(g_text),"v%%d-%%d",x,y); '
                    'ES(T,g_text);' % seed)
        elif k == 2:
            body = ('int x; g_init(%du); x=(int)(g_rnd()%%10000); '
                    '(void)snprintf_s(g_copy,sizeof(g_copy),"%%d",x); '
                    '(void)strncpy_s(g_text,sizeof(g_text),g_copy,strlen(g_copy)); '
                    'ES(T,g_text);' % seed)
        elif k == 3:
            body = ('long long a,s; g_init(%du); a=(long long)(g_rnd()%%13); '
                    '(void)memset_s(g_copy,sizeof(g_copy),65,sizeof(g_copy)); '
                    's=(long long)g_copy[63]; E(A,a); E(S,s);' % seed)
        else:
            body = ('long long a; int x; g_init(%du); a=(long long)(g_rnd()%%7); '
                    'x=(int)(g_rnd()%%50); '
                    '(void)snprintf_s(g_text,sizeof(g_text),"%%s/%%d","strict",x); '
                    'E(A,a); ES(T,g_text);' % seed)
        rows.append(("app_strict|s%d" % seed, " ".join(body.split())))
    os.makedirs(GEN, exist_ok=True)
    path = os.path.join(GEN, "app_strict.c")
    with open(path, "w") as f:
        f.write("/* GENERATED by generate.py -- do not edit. */\n")
        f.write("#define E2E_COUNT %d\n" % len(rows))
        f.write(STRICT_COMMON)
        f.write(STRICT_PROLOGUE)
        for i, (_, body) in enumerate(rows):
            f.write("static void sc_%04d(void) { %s }\n" % (i, body))
        f.write("\nstatic void e2e_dispatch(int idx) {\n")
        f.write("    switch (idx) {\n")
        for i, (_, _) in enumerate(rows):
            f.write("        case %d: sc_%04d(); break;\n" % (i, i))
        f.write("        default: break;\n    }\n}\n")
        f.write("\nstatic const e2e_scenario E2E_TAB[E2E_COUNT] = {\n")
        for i, (name, _) in enumerate(rows):
            rec = EXP.get(name, {})
            f.write('    {"%s", %s, %s, %d},\n' %
                    (name, json.dumps(rec.get("out", "")),
                     json.dumps(rec.get("err", "")), int(rec.get("exit", 0))))
        f.write("};\n")
        f.write('#include "strict_runner.h"\n')
        f.write("int main(void) {\n")
        for i in range(len(rows)):
            f.write("    e2e_one(%d);\n" % i)
        f.write("    return e2e_finish();\n}\n")
    return path


def api_files():
    files = []
    for g in load_base_groups():
        fb = FileBuilder(g.name, g.headers, g.prologue)
        for key, body, hint in g.rows:
            api = key.split("|", 1)[0]
            for count in CALL_COUNTS:
                calls = " ".join("{%s}" % body for _ in range(count))
                fb.add("%s|x%d" % (key, count), calls, "api")
            for factor in SCALES:
                vbody = scale_body(body, factor)
                fb.add("%s|p%d" % (key, factor), "{%s}" % vbody, "api")
        files.append(fb)
    return files


APP_HEADERS = ["apps_common.h"]


def app_board():
    fb = FileBuilder("app_board", APP_HEADERS)
    for seed in range(1, 121):
        body = ('char line[16]={0}; int w=0,m=0; app_tictactoe(%du,line,&w,&m); '
                'ES(B,line); E(W,w); E(M,m);' % seed)
        fb.add("app_tictactoe|s%d" % seed, body, "tic-tac-toe")
    for seed in range(1, 121):
        body = ('int sc=0,d=0; d=app_play2048(%du,%d,&sc); E(D,d); E(S,sc);'
                % (seed, 4 + seed % 12))
        fb.add("app_2048|s%d" % seed, body, "2048")
    for seed in range(1, 101):
        body = ('int p[2]={0},sc=0; app_snake(%du,%d,p,&sc); '
                'E(X,p[0]); E(Y,p[1]); E(S,sc);' % (seed, 10 + seed % 31))
        fb.add("app_snake|s%d" % seed, body, "snake")
    return fb


def app_text():
    fb = FileBuilder("app_text", APP_HEADERS)
    for seed in range(1, 101):
        body = ('int a=0,b=0,k=0,r=0; r=app_calc(%du,&a,&b,&k); '
                'E(A,a); E(B,b); E(O,k); E(R,r);' % seed)
        fb.add("app_calculator|s%d" % seed, body, "calculator")
    for seed in range(1, 101):
        body = 'char b[32]={0}; app_line_edit(%du,b,sizeof(b)); ES(L,b);' % seed
        fb.add("app_line_editor|s%d" % seed, body, "line-editor")
    for seed in range(1, 101):
        body = ('char t[64]={0}; unsigned long long h=app_hash_case(%du,t,sizeof(t)); '
                'ES(T,t); E(H,(long long)(h %% 1000000007ULL));' % seed)
        fb.add("app_hash|s%d" % seed, body, "hash")
    return fb


def app_sys():
    fb = FileBuilder("app_sys", APP_HEADERS + ["pthread.h"])
    prologue = """
static int app_worker_val(unsigned int seed, int idx) {
    unsigned int s = seed + (unsigned)idx * 37u + 101u;
    return (int)(app_rnd(&s) % 1000u);
}
"""
    fb.prologue = prologue
    for seed in range(1, 81):
        body = ('int i=0,t=0; for(i=0;i<4;i++) t+=app_worker_val(%du,i); '
                'E(T,t);' % seed)
        fb.add("app_thread|s%d" % seed, body, "thread")
    for seed in range(1, 81):
        body = ("""char nm[64]={0},buf[32]={0},h[17]={0}; FILE *f=NULL; size_t got=0;
                  (void)snprintf_s(nm,sizeof(nm),"scratch/e2e_file_%%d.tmp",%d);
                  f=fopen_s(nm,"w+b");
                  if(f){ (void)snprintf_s(buf,sizeof(buf),"rec-%%d",%d);
                         (void)fwrite_s(buf,sizeof(buf),1,strlen(buf),f);
                         (void)fflush(f); (void)rewind(f);
                         (void)memset_s(buf,sizeof(buf),0,sizeof(buf));
                         got=fread_s(buf,sizeof(buf),1,sizeof(buf)-1,f);
                         E(N,(long long)got); ES(D,buf);
                         app_hex(app_hash(buf,got),h); ES(H,h);
                         (void)fclose_s(f); (void)remove(nm); }
                  else E(N,-1);""" % (seed, seed))
        fb.add("app_file|s%d" % seed, body, "file")
    for seed in range(1, 101):
        body = ('int n=0; char w[32]={0}; int r=0; r=app_json_fields(%du,&n,w,sizeof(w)); '
                'E(R,r); E(N,n); ES(W,w);' % seed)
        fb.add("app_json|s%d" % seed, body, "json")
    return fb


def main():
    files = api_files() + [app_board(), app_text(), app_sys()]
    manifest = {
        "files": [fb.name + ".c" for fb in files],
        "scenario_count": sum(len(fb.rows) for fb in files),
        "categories": sorted({c for fb in files for c in fb.categories}),
        "call_counts": CALL_COUNTS,
        "scales": SCALES,
    }
    os.makedirs(GEN, exist_ok=True)
    for fb in files:
        fb.write()
    with open(os.path.join(GEN, "manifest.json"), "w") as f:
        json.dump(manifest, f, indent=2)
        f.write("\n")
    print("generated %d files, %d scenarios, %d categories" %
          (len(files), manifest["scenario_count"], len(manifest["categories"])))


if __name__ == "__main__":
    main()
