def formats(idx: int, n: int):
    v = idx % 10
    a = ri(1, 9999)
    fn = f"static void scn_{n:05d}(void)"
    if v == 0:
        return ([f"{fn}{{ printf(\"r=%d\\n\", {a}); }}"], f"r={a}\n", "", 0, True, False)
    if v == 1:
        return ([f"{fn}{{ printf(\"r=%08d\\n\", {a}); }}"], f"r={a:08d}\n", "", 0, True, False)
    if v == 2:
        return ([f"{fn}{{ printf(\"r=%-6d|\\n\", {a}); }}"], f"r={str(a):<6}|\n", "", 0, True, False)
    if v == 3:
        return ([f"{fn}{{ printf(\"r=%x\\n\", {a}); }}"], f"r={a:x}\n", "", 0, True, False)
    if v == 4:
        return ([f"{fn}{{ printf(\"r=%o\\n\", {a}); }}"], f"r={a:o}\n", "", 0, True, False)
    if v == 5:
        c = "ABCDEFG"[ri(0, 6)]
        return ([f"{fn}{{ printf(\"r=%c\\n\", '{c}'); }}"], f"r={c}\n", "", 0, True, False)
