def arith(idx: int, n: int):
    v = idx % 10
    a, b = ri(-900, 900), ri(-40, 40) or 7
    fn = f"static void scn_{n:05d}(void)"
    if v == 0:
        return ([f"{fn}{{ int a={a}, b={b}; printf(\"r=%d\\n\", a+b); }}"],
                f"r={a+b}\n", "", 0, True, False)
    if v == 1:
        a, b = ri(1, 2000), ri(1, 60)
        return ([f"{fn}{{ unsigned a={a}u, b={b}u; printf(\"r=%u\\n\", a*b); }}"],
                f"r={(a*b) & 0xFFFFFFFF}\n", "", 0, True, False)
    if v == 2:
        a, b = ri(-1000000, 1000000), ri(-500, 500)
        return ([f"{fn}{{ long long a={a}LL, b={b}LL; printf(\"r=%lld\\n\", a-b); }}"],
                f"r={a-b}\n", "", 0, True, False)
