#!/usr/bin/env python3
"""Deterministic end-to-end scenario generator for the C+ compiler core.

Emits 10 shard programs (510 named scenario functions each) plus one small
source file per compile-time-rejection scenario. Every shard is a full program:
its harness runs each named scenario in a forked child with a hard 2s timeout
and checks exact stdout/stderr/exit status, printing one PASS/FAIL line each.

The seed is fixed; all expected values are computed here. Regeneration is
byte-for-byte deterministic.
"""
