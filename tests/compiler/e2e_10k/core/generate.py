def ri(a: int, b: int) -> int:
    return R.randint(a, b)


def cstr(s: str) -> str:
    return json.dumps(s, ensure_ascii=True)


def rename_locals(body: list[str], suffix: str) -> list[str]:
    """Give every single-letter identifier a per-scenario suffix.

    The current c+ analyzer keeps stale symbol information across functions in
    a translation unit (e.g. a scalar `a` in one function inherits an earlier
    function's `int a[4]` extent). Unique names prevent that false positive.
    Strings and character literals are left untouched.
    """
    out = []
    for line in body:
        buf = []
        i = 0
        in_str = False
        in_chr = False
        while i < len(line):
            ch = line[i]
            if in_str:
                buf.append(ch)
                if ch == "\\" and i + 1 < len(line):
                    buf.append(line[i + 1])
                    i += 2
                    continue
                if ch == '"':
                    in_str = False
                i += 1
                continue
            if in_chr:
                buf.append(ch)
                if ch == "\\" and i + 1 < len(line):
                    buf.append(line[i + 1])
                    i += 2
                    continue
                if ch == "'":
                    in_chr = False
                i += 1
                continue
            if ch == '"':
                in_str = True
                buf.append(ch)
                i += 1
                continue
            if ch == "'":
                in_chr = True
                buf.append(ch)
                i += 1
                continue
            if "a" <= ch <= "z" and (i == 0 or not (line[i - 1].isalnum() or line[i - 1] == "_")) \
                    and (i + 1 == len(line) or not (line[i + 1].isalnum() or line[i + 1] == "_")):
                buf.append(ch + "_" + suffix)
                i += 1
                continue
            buf.append(ch)
            i += 1
        out.append("".join(buf))
    return out


class Shard:
    def __init__(self, idx: int, plan):
        self.idx = idx
        self.name = f"shard_{idx:02d}"
        self.path = f"generated/{self.name}.c"
        self.plan = plan
        self.is_cplus = idx == 6
        self.null_helper_line = 0
        self.lines: list[str] = []
        self.scenarios: list[dict] = []

    def emit(self, line: str) -> None:
        self.lines.append(line)

    def prelude(self) -> None:
        self.emit(f"/* AUTO-GENERATED by generate.py seed={SEED} -- do not edit. */")
        for h in ("stdio.h", "stdlib.h", "string.h", "limits.h", "stdint.h"):
            self.emit(f"#include <{h}>")
        if self.is_cplus:
            self.emit('#include "cplus/cplus.h"')
        for h in ("unistd.h", "poll.h", "signal.h", "sys/wait.h"):
            self.emit(f"#include <{h}>")
        self.emit("")
        self.emit("/* Opaque to static analysis, fixed at runtime => deterministic. */")
        self.emit("static volatile int OPAQUE = 3;")
        self.emit("static volatile int OPAQUE2 = 7;")
        self.emit("static int g_sink;")
        self.emit("")
        if self.is_cplus:
            self.emit("static int g_drops;")
            self.emit("resource struct RS { int id; };")
            self.emit("void RS_drop(RS *r) { if (r->id) { g_drops += r->id; r->id = 0; } }")
            self.emit("")
        self.null_helper_line = len(self.lines) + 1
        self.emit("static int null_helper(int *p){ int v = *p; return v; }")
        self.emit("")

    def add(self, name: str, cat: int, body: list[str], out: str, err: str,
            code: int, plain: bool, trap: bool) -> None:
        suffix = name.split("_")[-1]
        body = rename_locals(body, suffix)
        if "'a'" in err:
            err = err.replace("'a'", "'a_" + suffix + "'")
        for line in body:
            self.emit(line)
        self.emit("")
        self.scenarios.append({"name": name, "cat": cat,
                               "fn": "scn_" + suffix,
                               "flags": (F_TRAP if trap else F_SAFE) |
                                        (F_PLAIN if plain and not trap else 0),
                               "out": out, "err": err, "code": code})

    def harness(self) -> None:
        entries = []
        for s in self.scenarios:
            entries.append("  {%s, %s, %d, %d, %s, %s, %d}," %
                           (cstr(s["name"]), s["fn"], s["cat"], s["flags"],
                            cstr(s["out"]), cstr(s["err"]), s["code"]))
        for line in HARNESS.replace("@@MANIFEST@@", "\n".join(entries)).splitlines():
            self.emit(line)

    def write(self) -> None:
        with open(os.path.join(GEN_DIR, self.name + ".c"), "w") as f:
            f.write("\n".join(self.lines) + "\n")


HARNESS = r'''
typedef void (*ScnFn)(void);
enum { F_SAFE = 1, F_TRAP = 2, F_PLAIN = 4 };
typedef struct { const char *name; ScnFn fn; int cat; int flags;
                 const char *out; const char *err; int code; } Scn;

static const Scn SCNS[] = {
@@MANIFEST@@
};
static const int NS = (int)(sizeof(SCNS)/sizeof(SCNS[0]));

/* One forked child per scenario; hard 2s timeout; exact stdout/stderr/exit.
   Trap scenarios cannot corrupt the harness or each other. */
static int run_one(const Scn *s, char *detail, size_t cap){
  int po[2], pe[2];
  if(pipe(po)!=0 || pipe(pe)!=0){ snprintf(detail,cap,"pipe failed"); return 0; }
  fflush(stdout); fflush(stderr); /* children must not inherit parent's buffered PASS lines */
  pid_t pid = fork();
  if(pid<0){ snprintf(detail,cap,"fork failed"); return 0; }
  if(pid==0){
    close(po[0]); close(pe[0]);
    dup2(po[1],1); dup2(pe[1],2); close(po[1]); close(pe[1]);
    s->fn(); fflush(stdout); fflush(stderr); _exit(0);
  }
  close(po[1]); close(pe[1]);
  char ob[8192], eb[8192];
  size_t on=0, en=0; ob[0]=0; eb[0]=0;
  struct pollfd fds[2];
  fds[0].fd=po[0]; fds[0].events=POLLIN; fds[0].revents=0;
  fds[1].fd=pe[0]; fds[1].events=POLLIN; fds[1].revents=0;
  int timedout=0;
  for(int iter=0; iter<20; iter++){
    int n=poll(fds,2,100);
    if(n<0){ timedout=1; break; }
    if(fds[0].revents){
      ssize_t r=read(po[0],ob+on,sizeof(ob)-1-on);
      if(r>0){ on+=(size_t)r; ob[on]=0; } else { fds[0].fd=-1; }
    }
    if(fds[1].revents){
      ssize_t r=read(pe[0],eb+en,sizeof(eb)-1-en);
      if(r>0){ en+=(size_t)r; eb[en]=0; } else { fds[1].fd=-1; }
    }
    if(fds[0].fd<0 && fds[1].fd<0) break;
    if(iter==19) timedout=1;
  }
  close(po[0]); close(pe[0]);
  int status=0; waitpid(pid,&status,0);
  if(timedout){ kill(pid,SIGKILL); status=0; waitpid(pid,&status,0);
    snprintf(detail,cap,"TIMEOUT expected=[%s]",s->out); return 0; }
  int code = WIFSIGNALED(status) ? 128+WTERMSIG(status) : WEXITSTATUS(status);
  int ok = strcmp(ob,s->out)==0 && strcmp(eb,s->err)==0 && code==s->code;
  if(ok){ snprintf(detail,cap,"exit=%d out=[%s] err=[%s]",code,ob,eb); return 1; }
  snprintf(detail,cap,"expected(code=%d,out=[%s],err=[%s]) got(code=%d,out=[%s],err=[%s])",
           s->code,s->out,s->err,code,ob,eb);
  return 0;
}

int main(int argc,char **argv){
  int mode = argc>1 ? atoi(argv[1]) : 0; /* 0 safe, 1 trap, 2 plain-C cross-check */
  int pass=0, fail=0;
  for(int i=0;i<NS;i++){
    const Scn *s=&SCNS[i];
    if(mode==0 && !(s->flags&F_SAFE)) continue;
    if(mode==1 && !(s->flags&F_TRAP)) continue;
    if(mode==2 && !((s->flags&F_SAFE)&&(s->flags&F_PLAIN))) continue;
    char detail[4096]; detail[0]=0;
    int ok=run_one(s,detail,sizeof(detail));
    if(ok) pass++; else fail++;
    printf("%s %s cat=%d mode=%d %s\n",ok?"PASS":"FAIL",s->name,s->cat,mode,detail);
  }
  printf("SUMMARY mode=%d total=%d pass=%d fail=%d\n",mode,pass+fail,pass,fail);
  return fail?1:0;
}
'''

