def guards(idx: int, n: int, sh: Shard):
    v = idx % 10
    a = ri(1, 900)
    fn = f"static void scn_{n:05d}(void)"
    if v == 0:
        return ([f"{fn}{{ int a[8]={{1,2,3,4,5,6,7,8}}; int i=OPAQUE-3; if(i>=0 && i<8) printf(\"r=%d\\n\", a[i]); else printf(\"r=-1\\n\"); }}"],
                "r=1\n", "", 0, True, False)
    if v == 1:
        return ([f"{fn}{{ int d=OPAQUE-3; if(d) printf(\"r=%d\\n\", {a}/d); else printf(\"r=guard\\n\"); }}"],
                "r=guard\n", "", 0, True, False)
    if v == 2:
        return ([f"{fn}{{ int *p=(OPAQUE>0)?&g_sink:NULL; if(p){{ *p={a}; printf(\"r=%d\\n\", *p); }} else printf(\"r=null\\n\"); }}"],
                f"r={a}\n", "", 0, True, False)
    if v == 3:
        return ([f"{fn}{{ int z=OPAQUE-3; printf(\"r=%d\\n\", {a}/z); }}"],
                "", "C+ runtime error: division by zero: division by zero\n", 110, False, True)
    if v == 4:
        return ([f"{fn}{{ int z=OPAQUE-3; printf(\"r=%d\\n\", {a}%z); }}"],
                "", "C+ runtime error: division by zero: remainder by zero\n", 110, False, True)
    if v == 5:
        return ([f"{fn}{{ int x=2147483647; printf(\"r=%d\\n\", x+OPAQUE); }}"], "",
                "C+ runtime error: signed integer overflow: addition result does not fit in a 32-bit signed integer\n", 110, False, True)
    if v == 6:
        return ([f"{fn}{{ int x=2147483647; printf(\"r=%d\\n\", x*OPAQUE); }}"], "",
                "C+ runtime error: signed integer overflow: multiplication result does not fit in a 32-bit signed integer\n", 110, False, True)
    if v == 7:
        return ([f"{fn}{{ int a[4]={{1,2,3,4}}; printf(\"r=%d\\n\", a[OPAQUE+2]); }}"], "",
                "C+ error: index 5 is outside the bounds of 'a' (length 4)\n", 134, False, True)
    if v == 8:
        return ([f"{fn}{{ int x=-2147483647-1; printf(\"r=%d\\n\", -x); }}"], "",
                "C+ runtime error: signed integer overflow: subtraction result does not fit in a 32-bit signed integer\n", 110, False, True)
    err = ("C+ runtime error: null pointer dereference at %s:%d: null pointer dereference (p)\n"
           % (sh.path, sh.null_helper_line))
    return ([f"{fn}{{ printf(\"r=%d\\n\", null_helper(NULL)); }}"], "", err, 102, False, True)


