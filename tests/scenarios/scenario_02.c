static unsigned long g_refused = 0;
static unsigned long g_allowed = 0;
static unsigned long g_findings = 0;
static const safe02_tuple *g_cur_tuple = NULL;
static unsigned long g_cur_index = 0;

static void finding(unsigned long idx, const safe02_tuple *t, const char *why)
{
    ++g_findings;
    printf("FINDING scenario_02 case %lu (initial=%zu grow=%zu shrink=%zu "
           "off=%zu len=%zu): %s\n",
           idx, t->initial_size, t->grow_size, t->shrink_size,
           t->alias_offset, t->access_len, why);
}

/* Crash path: emit the exact tuple, then exit nonzero so the harness fails. */
static void crash_handler(int sig)
{
    char msg[256];
    int n;
    const safe02_tuple *t = g_cur_tuple;
    if (t != NULL) {
        n = snprintf(msg, sizeof msg,
                     "FINDING scenario_02 case %lu (initial=%zu grow=%zu "
                     "shrink=%zu off=%zu len=%zu): crash signal %d\n",
                     g_cur_index, t->initial_size, t->grow_size,
                     t->shrink_size, t->alias_offset, t->access_len, sig);
    } else {
        n = snprintf(msg, sizeof msg,
                     "FINDING scenario_02: crash signal %d outside case\n", sig);
    }
    if (n > 0) {
        if (n > (int)sizeof msg) n = (int)sizeof msg;
        (void)write(STDERR_FILENO, msg, (size_t)n);
    }
    _exit(2);
}

static void run_case(unsigned long idx, const safe02_tuple *t)
{
    unsigned char *p = NULL;
    unsigned char *cur = NULL;
    size_t cur_size = 0;
    unsigned char expected[MAX_BUF];
    unsigned char observed[MAX_BUF];
    int kind = (int)(idx % 8u);
    size_t i;

    p = (unsigned char *)malloc(t->initial_size);   /* hardened malloc_s */
    if (p == NULL) { finding(idx, t, "initial malloc failed"); return; }
    cur = p;
    cur_size = t->initial_size;
    memset(p, PATTERN, t->initial_size);           /* hardened memset_s */

    switch (kind) {
    case 0:  /* grow to large, then shrink to tiny (realloc chain) */
    {
        unsigned char *q = (unsigned char *)realloc(cur, t->grow_size);
        if (q == NULL) { finding(idx, t, "grow realloc failed"); goto done; }
        cur = q; cur_size = t->grow_size;
        q = (unsigned char *)realloc(cur, t->shrink_size);
        if (q == NULL) { finding(idx, t, "shrink realloc failed"); goto done; }
        cur = q; cur_size = t->shrink_size;
        break;
    }
    case 1:  /* grow only */
    case 3:  /* equal-size realloc */
    {
        size_t target = (kind == 1) ? t->grow_size : t->initial_size;
        unsigned char *q = (unsigned char *)realloc(cur, target);
        if (q == NULL) { finding(idx, t, "single realloc failed"); goto done; }
        cur = q; cur_size = target;
        break;
    }
    case 2:  /* shrink only */
    {
        unsigned char *q = (unsigned char *)realloc(cur, t->shrink_size);
        if (q == NULL) { finding(idx, t, "shrink realloc failed"); goto done; }
        cur = q; cur_size = t->shrink_size;
        break;
    }
    case 4:  /* realloc(NULL, grow) after the original block was freed */
        free(cur);                       /* hardened free_s */
        cur = NULL; cur_size = 0;
        cur = (unsigned char *)realloc(NULL, t->grow_size);
        if (cur == NULL) { finding(idx, t, "realloc(NULL) failed"); goto done; }
        cur_size = t->grow_size;
        break;
    case 5:  /* realloc(p, 0): tracked block shrinks to its 1-byte form */
    {
        unsigned char *q = (unsigned char *)realloc(cur, 0);
        if (q == NULL) { finding(idx, t, "realloc(p,0) failed"); goto done; }
        cur = q; cur_size = 1u;
        break;
    }
    case 6:  /* failure injection: owned block must survive failed realloc */
    {
        long n = (long)(idx % 4u);
        size_t before = cur_size;
        int failed = 0;
        int step;
        cplus_safe_alloc_fail_after(n);
        for (step = 0; step <= n; ++step) {
            size_t target = (step % 2 == 0) ? t->grow_size : t->shrink_size;
            unsigned char *q = (unsigned char *)realloc(cur, target);
            if (q == NULL) { failed = 1; break; }
            cur = q; cur_size = target;
        }
        cplus_safe_alloc_fail_reset();   /* reset after every case */
        if (!failed) {
            finding(idx, t, "injected allocation failure did not occur");
        } else if (!cplus_safe_ptr_is_live(cur)) {
            finding(idx, t, "failed realloc dropped live ownership");
        } else {
            size_t keep = before < cur_size ? before : cur_size;
            if (keep > MAX_BUF) { finding(idx, t, "scratch overflow"); goto done; }
            (void)memcpy(observed, cur, keep);          /* hardened copy */
            for (i = 0; i < keep; ++i) expected[i] = PATTERN;
            for (i = 0; i < keep; ++i) {
                if (observed[i] != expected[i]) {
                    finding(idx, t, "failed realloc corrupted preserved bytes");
                    break;
                }
            }
        }
        break;
    }
    case 7:  /* repeated realloc chain: grow/shrink/grow/equal */
    {
        size_t targets[4];
        int k;
        targets[0] = t->grow_size;  targets[1] = t->shrink_size;
        targets[2] = t->grow_size;  targets[3] = t->initial_size;
        for (k = 0; k < 4; ++k) {
            unsigned char *q = (unsigned char *)realloc(cur, targets[k]);
            if (q == NULL) { finding(idx, t, "chain realloc failed"); goto done; }
            cur = q; cur_size = targets[k];
        }
        break;
    }
    default:
        finding(idx, t, "unknown case kind");
        goto done;
    }

    if (cur_size == 0 || cur_size > MAX_BUF || t->access_len > MAX_BUF) {
        finding(idx, t, "case exceeds bounded scratch buffers");
        goto done;
    }

    /* Build the exact expected contents on the stack, then plant them with a
     * SINGLE hardened memcpy through the live base pointer.  The alias offset
     * is deliberately allowed to be past the final block: that is one of the
     * stale-pointer shapes under test and must be REFUSED, not treated as a
     * harness error.  Interior-pointer setup writes are avoided because the
     * bounded recent-free cache can (a documented limitation) misclassify a
     * recycled interior address as freed and refuse a harmless canary store. */
    for (i = 0; i < cur_size; ++i) {
        unsigned char want = (i == 0) ? CANARY_FRONT : PATTERN;
        if (i == cur_size - 1u) want = CANARY_BACK;
        expected[i] = want;
    }
    (void)memcpy(cur, expected, cur_size);   /* hardened, base pointer only */

    /* Stale alias: integer arithmetic only; the write itself goes through
     * the hardened memset macro (never a raw store). */
    {
        unsigned char *alias =
            (unsigned char *)((uintptr_t)p + (uintptr_t)t->alias_offset);
        errno = 0;
        (void)memset(alias, WRITE_BYTE, t->access_len);
    }

    /* Read back only through the hardened memcpy macro. */
    (void)memcpy(observed, cur, cur_size);

    {
        /* A moved block can put the OLD alias at a DIFFERENT offset inside the
         * NEW block (or entirely outside it).  Compute the real offset from
         * addresses, never from the original alias_offset. */
        uintptr_t alias_addr = (uintptr_t)p + (uintptr_t)t->alias_offset;
        uintptr_t base_addr = (uintptr_t)cur;
        size_t rel = t->alias_offset;
        size_t end;
        int wrote = 0;
        if (alias_addr >= base_addr &&
            (alias_addr - base_addr) < (uintptr_t)cur_size) {
            rel = (size_t)(alias_addr - base_addr);
        }
        end = rel + t->access_len;   /* bounded small values; no overflow */
        for (i = rel; i < cur_size && i < end; ++i) {
            if (observed[i] == WRITE_BYTE) { wrote = 1; break; }
        }
        if (wrote) {
            ++g_allowed;
            if (end > cur_size)
                finding(idx, t, "stale alias wrote outside the new allocation");
        } else {
            ++g_refused;
        }
        for (i = 0; i < cur_size; ++i) {
            unsigned char want = expected[i];   /* baseline planted above */
            if (wrote && i >= rel && i < end) want = WRITE_BYTE;
            if (observed[i] != want) {
                printf("FINDING scenario_02 case %lu (initial=%zu grow=%zu shrink=%zu "
                       "off=%zu len=%zu): byte %zu observed=0x%02x want=0x%02x "
                       "cur_size=%zu wrote=%d end=%zu\n",
                       idx, t->initial_size, t->grow_size, t->shrink_size,
                       t->alias_offset, t->access_len, i,
                       (unsigned)observed[i], (unsigned)want,
                       cur_size, wrote, end);
                ++g_findings;
                break;
            }
        }
    }

done:
    free(cur);   /* hardened free_s; cur is live or NULL */
}

int main(void)
{
    unsigned long i, j;

    /* Refusals must be reported, not fatal; unknown capacity must be
     * refused so a moved-block alias cannot write into freed memory. */
    cplus_runtime_set_violation_trap(0);
    cplus_safe_set_unknown_capacity_mode(1);
    signal(SIGSEGV, crash_handler);
    signal(SIGBUS, crash_handler);
    signal(SIGILL, crash_handler);
    signal(SIGFPE, crash_handler);

    /* Prove the table really holds distinct tuples. */
    for (i = 0; i < NCASES; ++i) {
        for (j = i + 1u; j < NCASES; ++j) {
            const safe02_tuple *a = &g_cases[i];
            const safe02_tuple *b = &g_cases[j];
            if (a->initial_size == b->initial_size &&
                a->grow_size == b->grow_size &&
                a->shrink_size == b->shrink_size &&
                a->alias_offset == b->alias_offset &&
                a->access_len == b->access_len) {
                finding(j, b, "duplicate tuple in scenario table");
            }
        }
    }

    for (i = 0; i < NCASES; ++i) {
        g_cur_index = i;
        g_cur_tuple = &g_cases[i];
        cplus_safe_alloc_fail_reset();   /* reset at every case boundary */
        run_case(i, &g_cases[i]);
    }
    g_cur_tuple = NULL;

    printf("scenario_02: refused=%lu allowed_in_bounds=%lu findings=%lu\n",
           g_refused, g_allowed, g_findings);
    if (g_findings == 0) {
        printf("scenario_02: %d cases ok\n", NCASES);
        return 0;
    }
    printf("scenario_02: %d cases failed\n", NCASES);
    return 1;
}
