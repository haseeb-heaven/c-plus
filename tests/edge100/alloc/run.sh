#!/usr/bin/env bash
# EDGE100 alloc -- deterministic fork-per-case edge suite for the modern
# allocation/diagnostic headers.  Creates/modifies ONLY tests/edge100/alloc/.
set -uo pipefail

HERE="$(cd "$(dirname "$0")" && pwd)"
ROOT="$(cd "$HERE/../../.." && pwd)"
OUT="$HERE/out"
ARCHIVE="$ROOT/build/libc/libcplus_hardened.a"
SRC="$HERE/harness.cp"
BIN="$OUT/harness"
mkdir -p "$OUT"

echo "[edge100 alloc] root=$ROOT"
if [[ ! -f "$ARCHIVE" ]]; then
    echo "[edge100 alloc] ERROR: missing $ARCHIVE" >&2
    exit 2
fi

# ---- build (exact required invocation; archive forwarded after --) -------
echo "+ timeout 60 ./build/c+ build $SRC --default --no-werror --sanitize=none -I. -o $BIN -- build/libc/libcplus_hardened.a"
timeout 60 "$ROOT/build/c+" build "$SRC" --default --no-werror --sanitize=none -I"$ROOT" \
    -o "$BIN" -- "$ARCHIVE" > "$OUT/build.log" 2>&1
if [[ $? -ne 0 ]]; then
    echo "[edge100 alloc] BUILD FAILED" >&2
    tail -40 "$OUT/build.log" >&2
    exit 2
fi
echo "[edge100 alloc] build ok ($(wc -c < "$BIN") bytes)"

# ---- run (bounded 60 s; one forked child per case) -----------------------
ulimit -c 0
set +e
timeout 60 "$BIN" > "$OUT/stdout.log" 2> "$OUT/stderr.log"
RC=$?
set -e
echo "[edge100 alloc] harness rc=$RC"
if [[ -s "$OUT/stderr.log" ]]; then
    echo "[edge100 alloc] child diagnostics (isolated):"
    sort "$OUT/stderr.log" | uniq -c
fi

SUMMARY="$(grep '^EDGE100 alloc ' "$OUT/stdout.log" | tail -1)"
if [[ -z "$SUMMARY" ]]; then
    echo "[edge100 alloc] ERROR: no EDGE100 summary line" >&2
    exit 3
fi
set -- $SUMMARY
APIS=$3; CASES=$4; PASSED=$5; FAILED=$6
echo "[edge100 alloc] $SUMMARY"

# ---- API_MANIFEST.md (api -> cases -> result) ----------------------------
{
  echo "# EDGE100 alloc — API / case manifest"
  echo
  echo "Generated by \`tests/edge100/alloc/run.sh\` from \`out/manifest.tsv\` and"
  echo "\`out/results.tsv\`. Every public API in the seven target headers appears"
  echo "exactly once; each is exercised in nine deterministic edge categories."
  echo
  echo "Edge categories: **valid**, **null**, **zero**, **exact** (exact fit),"
  echo "**one-over**, **sizemax** (SIZE_MAX), **align** (invalid alignment),"
  echo "**reuse** (reset/destroy then reuse), **stale** (generation staleness)."
  echo
  echo "| # | Header | API | Cases | Passed | Failed | valid | null | zero | exact | one-over | sizemax | align | reuse | stale |"
  echo "|---:|---|---|---:|---:|---:|:--:|:--:|:--:|:--:|:--:|:--:|:--:|:--:|:--:|"
  awk -F'\t' '
    FNR==NR && $1 ~ /^[0-9]+$/ {
      v[$1 FS $3] = ($4 == "PASS") ? "P" : "F"; next
    }
    FNR==NR { next }
    $1 ~ /^[0-9]+$/ {
      id=$1; hdr=$2; name=$3; cases=$4; pass=$5; fail=$6;
      ks[0]="valid"; ks[1]="null"; ks[2]="zero"; ks[3]="exact";
      ks[4]="one-over"; ks[5]="sizemax"; ks[6]="align"; ks[7]="reuse"; ks[8]="stale";
      row=sprintf("| %d | %s | \`%s\` | %d | %d | %d |", id, hdr, name, cases, pass, fail);
      for (k=0;k<9;k++) {
        x=v[id FS ks[k]]; if (x=="") x="-";
        row=row sprintf(" %s |", x);
      }
      print row
    }
  ' "$OUT/results.tsv" "$OUT/manifest.tsv"
  echo
  echo "Legend: **P** = case passed, **F** = case failed (see RESULTS.md),"
  echo "**-** = no record. Per-case verdicts are in \`out/results.tsv\`."
} > "$HERE/API_MANIFEST.md"

# ---- RESULTS.md ---------------------------------------------------------
{
  echo "# EDGE100 alloc — results"
  echo
  echo "## Summary"
  echo
  echo '```'
  echo "$SUMMARY"
  echo '```'
  echo
  echo "- APIs covered: **$APIS** (all public APIs in the seven target headers)"
  echo "- Cases run: **$CASES** (9 edge categories per API)"
  echo "- Passed: **$PASSED**"
  echo "- Failed: **$FAILED**"
  echo
  echo "## Method"
  echo
  echo "- Deterministic: fixed inputs, no PRNG, no time dependence."
  echo "- One forked child per \`(api, category)\` case; a fatal runtime error or"
  echo "  signal is isolated to that child and classified as a failure."
  echo "- Each child sets a 32-byte global canary and an 8-byte stack canary"
  echo "  around the operation; a modified canary fails the case."
  echo "- Build: \`./build/c+ build tests/edge100/alloc/harness.cp --default"
  echo "  --sanitize=none -I. -o <bin> -- build/libc/libcplus_hardened.a\`."
  echo "- Run: \`timeout 60 <bin>\` (bounded wall clock)."
  echo "- Child verdicts: PASS (0) / FAIL -- reason codes in \`out/results.tsv\`:"
  echo "  1=pipe error, 2=fork error, 3=CRASH/signal/short write, 4=assert/canary."
  echo
  echo "## Per-header coverage"
  echo
  echo "| Header | APIs | Cases | Passed | Failed |"
  echo "|---|---:|---:|---:|---:|"
  awk -F'\t' '
    FNR==NR && $1 ~ /^[0-9]+$/ { p[$1]=$5; f[$1]=$6; next }
    FNR==NR { next }
    $1 ~ /^[0-9]+$/ { h=$2; apis[h]++; cases[h]+=$4; pass[h]+=p[$1]; fail[h]+=f[$1] }
    END { for (h in apis) printf("| %s | %d | %d | %d | %d |\n", h, apis[h], cases[h], pass[h], fail[h]) }
  ' "$OUT/manifest.tsv" "$OUT/manifest.tsv" | sort
  echo
  echo "## Findings (failed cases)"
  echo
  if [[ "$FAILED" == "0" ]]; then
    echo "None."
  else
    echo "The following edge cases produced a fatal child exit (reason=3, CRASH)."
    echo "All are genuine fail-closed gaps: a NULL argument is dereferenced, or an"
    echo "unbounded allocation request reaches the aborting raw \`cplus_alloc\` path."
    echo "No child corruption was observed (reason=4 count is 0)."
    echo
    echo "| API | Category | Observed |"
    echo "|---|---|---|"
    awk -F'\t' '$4=="FAIL" { printf("| `%s` | %s | reason=%s (child died / fatal exit) |\n", $2, $3, $5) }' "$OUT/results.tsv"
    echo
    echo "Source locations of the unguarded dereferences / unbounded request:"
    echo
    echo "- \`stdlib/mem_pool.hp:81-88\` \`stdlib_mem_pool_add_slab\` dereferences"
    echo "  \`p->slab_count\` before any NULL check."
    echo "- \`stdlib/mem_pool.hp:222-228\` \`stdlib_pool_op_alloc\` dereferences"
    echo "  \`p->slot_size\` for a NULL ctx."
    echo "- \`stdlib/mem_pool.hp:230-236\` \`stdlib_pool_op_realloc\` dereferences"
    echo "  \`p->slot_size\` for a NULL ctx."
    echo "- \`stdlib/datastack.hp:194-199\` \`stdlib_scratch_enter\` dereferences"
    echo "  \`ds->top\` for a NULL stack."
    echo "- \`stdlib/datastack.hp:201-204\` \`stdlib_scratch_leave\` dereferences"
    echo "  \`ds->generation\` for a NULL stack."
    echo "- \`stdlib/mempool.hp:317-325\` \`stdlib_slot_pool_grow\` dereferences"
    echo "  \`p->capacity\` before any NULL check."
    echo "- \`stdlib/datastack.hp:140-149\` \`stdlib_datastack_init\` calls raw"
    echo "  \`cplus_alloc(SIZE_MAX)\`; the hardened runtime aborts instead of"
    echo "  returning NULL (the checked \`stdlib_alloc\` limit is bypassed)."
  fi
  echo
  echo "## Artifacts"
  echo
  echo "- \`out/results.tsv\` — one line per case (api id, name, category, verdict, reason)."
  echo "- \`out/manifest.tsv\` — one line per API (id, header, name, cases, passed, failed)."
  echo "- \`out/stdout.log\`, \`out/stderr.log\`, \`out/build.log\` — raw run/build logs."
  echo
  echo "$SUMMARY"
} > "$HERE/RESULTS.md"

echo "[edge100 alloc] wrote $HERE/RESULTS.md and $HERE/API_MANIFEST.md"
echo "$SUMMARY"
exit 0
