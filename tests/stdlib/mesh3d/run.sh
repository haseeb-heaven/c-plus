#!/bin/sh
# Build and run the mesh3d.hp verification suite, then (re)generate RESULTS.md.
#
# Usage:  sh tests/stdlib/mesh3d/run.sh
#
# The build uses the repository's standard C+ driver with the checked libc
# archive.  Every program stdout line must be "<tag> 1 1 ...": any 0, any
# malformed token, any stderr output, or a timeout fails the run.
set -u

DIR=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd) || exit 2
ROOT=$(CDPATH= cd -- "$DIR/../../.." && pwd) || exit 2
cd "$ROOT" || exit 2

CPLUS=${CPLUS_BIN:-"$ROOT/build/c+"}
OUT=${MESH3D_OUT:-"$DIR/.run"}
BIN="$OUT/test_mesh3d"
BUILD_LOG="$OUT/build.log"
STDOUT="$OUT/stdout.txt"
STDERR="$OUT/stderr.txt"
MIN_CHECKS=37

mkdir -p "$OUT" || exit 2
if [ ! -x "$CPLUS" ]; then
    echo "error: C+ compiler missing: $CPLUS (build it first)" >&2
    exit 2
fi
if ! command -v timeout >/dev/null 2>&1; then
    echo "error: 'timeout' utility not found; refusing unbounded test" >&2
    exit 2
fi

rm -f "$BIN" "$BUILD_LOG" "$STDOUT" "$STDERR"

# Canonical build line for this library family.
if ! timeout -k 5 120 "$CPLUS" build tests/stdlib/mesh3d/test_mesh3d.cp \
        --default --no-werror --sanitize=none -I. -o "$BIN" \
        -- build/libc/libcplus_hardened.a >"$BUILD_LOG" 2>&1; then
    echo "BUILD FAIL: see $BUILD_LOG" >&2
    tail -n 20 "$BUILD_LOG" >&2
    exit 1
fi
if [ ! -x "$BIN" ]; then
    echo "BUILD FAIL: no executable produced" >&2
    exit 1
fi

timeout -k 5 60 "$BIN" </dev/null >"$STDOUT" 2>"$STDERR"
RUN_RC=$?
if [ "$RUN_RC" -eq 124 ] || [ "$RUN_RC" -ge 128 ]; then
    echo "TIMEOUT: mesh3d test exceeded 60s (rc=$RUN_RC)" >&2
    exit 1
fi

read -r CHECKS FAILURES MALFORMED <<EOF
$(awk '
{
    if ($1 !~ /^[a-z][a-z0-9-]*$/) { malformed++; next }
    checks++
    for (i = 2; i <= NF; i++) {
        if ($i != "0" && $i != "1") { malformed++; continue }
        if ($i == "0") failures++
    }
}
END { print checks+0, failures+0, malformed+0 }
' "$STDOUT")
EOF

STATUS=PASS
WHY="all checks returned 1; stderr empty"
if [ "$RUN_RC" -ne 0 ]; then
    STATUS=FAIL
    WHY="program exit $RUN_RC"
elif [ -s "$STDERR" ]; then
    STATUS=FAIL
    WHY="unexpected stderr output"
elif [ "$MALFORMED" -ne 0 ]; then
    STATUS=FAIL
    WHY="malformed output tokens: $MALFORMED"
elif [ "$FAILURES" -ne 0 ]; then
    STATUS=FAIL
    WHY="failed assertions: $FAILURES"
elif [ "$CHECKS" -lt "$MIN_CHECKS" ]; then
    STATUS=FAIL
    WHY="only $CHECKS checks (expected >= $MIN_CHECKS)"
fi

{
    printf '# mesh3d.hp verification results\n\n'
    printf 'Generated by `sh tests/stdlib/mesh3d/run.sh`.\n\n'
    printf '## Build\n\n'
    printf '```sh\n'
    printf './build/c+ build tests/stdlib/mesh3d/test_mesh3d.cp \\\n'
    printf '    --default --no-werror --sanitize=none -I. \\\n'
    printf '    -o tests/stdlib/mesh3d/.run/test_mesh3d \\\n'
    printf '    -- build/libc/libcplus_hardened.a\n'
    printf '```\n\n'
    printf '## Result\n\n'
    printf -- '- Status: **%s**\n' "$STATUS"
    printf -- '- Checks: %s\n' "$CHECKS"
    printf -- '- Failures: %s\n' "$FAILURES"
    printf -- '- Malformed lines: %s\n' "$MALFORMED"
    printf -- '- Program exit: %s\n' "$RUN_RC"
    printf -- '- Detail: %s\n\n' "$WHY"
    printf '## Coverage\n\n'
    printf '| Area | Tags |\n'
    printf '| --- | --- |\n'
    printf '| Lifecycle / counts | init, build, clear, reuse-after-clear, drop |\n'
    printf '| Bounding box / center | bbox, center, transformed, single-center, empty-center-refused |\n'
    printf '| Normals | normals-ok, normals-unit, normals-outward, normals-exact |\n'
    printf '| Validation | validate-clean, validate-degenerate, validate-bad-index, validate-restored |\n'
    printf '| Refusals | refuse-index, refuse-repeat-index, refuse-nan-vertex, refuse-inf-vertex, refuse-collinear, refuse-nan-scale, refuse-inf-translate, refuse-overflow-scale, refuse-oversized-vertices, refuse-oversized-triangles, refuse-at |\n'
    printf '| Atomicity | scale-atomic, translate-atomic |\n'
    printf '| Allocator | custom-init, custom-build, custom-drop, custom-double-drop |\n\n'
    printf '## Raw output\n\n'
    printf '```\n'
    cat "$STDOUT"
    printf '```\n'
} > "$DIR/RESULTS.md"

printf 'MESH3D %s %s\n' "$CHECKS" "$FAILURES"
if [ "$STATUS" != PASS ]; then
    echo "FAIL: $WHY" >&2
    exit 1
fi
exit 0
