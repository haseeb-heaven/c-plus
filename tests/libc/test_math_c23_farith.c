static void test_exact_vectors(void) {
    size_t i;
    for (i = 0; i < sizeof kExactVectors / sizeof kExactVectors[0]; ++i) {
        const int op = kExactVectors[i].op;
        const double x = frombits_d(kExactVectors[i].x);
        const double y = frombits_d(kExactVectors[i].y);
        const uint32_t want = kExactVectors[i].want;
        float rd, rl;

        switch (op) {
        case FARITH_FADD: rd = cplus_fadd(x, y); rl = cplus_faddl((long double)x, (long double)y); break;
        case FARITH_FSUB: rd = cplus_fsub(x, y); rl = cplus_fsubl((long double)x, (long double)y); break;
        case FARITH_FMUL: rd = cplus_fmul(x, y); rl = cplus_fmull((long double)x, (long double)y); break;
        case FARITH_FDIV: rd = cplus_fdiv(x, y); rl = cplus_fdivl((long double)x, (long double)y); break;
        default: continue;
        }
        CHECK(bits_f(rd) == want, "exact oracle: double-operand wrapper");
        CHECK(bits_f(rl) == want, "exact oracle: long-double-operand wrapper");
    }
}

static void test_special_values(void) {
    const double inf = INFINITY;
    const double nan = NAN;
    const double dmax = DBL_MAX;

    /* Signed zero: IEEE 754 rules that C23 Annex F says the narrowing
     * operations inherit from the corresponding operator. */
    CHECK(bits_f(cplus_fadd(-0.0, -0.0)) == 0x80000000u, "fadd(-0,-0) -> -0");
    CHECK(bits_f(cplus_fadd( 0.0, -0.0)) == 0x00000000u, "fadd(+0,-0) -> +0");
    CHECK(bits_f(cplus_fsub( 0.0,  0.0)) == 0x00000000u, "fsub(+0,+0) -> +0");
    CHECK(bits_f(cplus_fsub(-0.0,  0.0)) == 0x80000000u, "fsub(-0,+0) -> -0");
    CHECK(bits_f(cplus_fmul(-1.0,  0.0)) == 0x80000000u, "fmul(-1,+0) -> -0");
    CHECK(bits_f(cplus_fdiv(-1.0,  inf)) == 0x80000000u, "fdiv(-1,+inf) -> -0");
    CHECK(bits_f(cplus_faddl((long double)-0.0L, (long double)-0.0L)) == 0x80000000u,
          "faddl(-0,-0) -> -0");

    /* NaN propagation and invalid operations. */
    CHECK(isnan(cplus_fadd(inf, -inf)), "fadd(+inf,-inf) -> NaN");
    CHECK(isnan(cplus_fsub(inf,  inf)), "fsub(+inf,+inf) -> NaN");
    CHECK(isnan(cplus_fmul(0.0,  inf)), "fmul(+0,+inf) -> NaN");
    CHECK(isnan(cplus_fdiv(0.0,  0.0)), "fdiv(+0,+0) -> NaN");
    CHECK(isnan(cplus_fdiv(inf,  inf)), "fdiv(+inf,+inf) -> NaN");
    CHECK(isnan(cplus_fadd(nan, 1.0)), "fadd(NaN,1) -> NaN");
    CHECK(isnan(cplus_fmul(nan, 0.0)), "fmul(NaN,0) -> NaN");
    CHECK(isnan(cplus_fsubl((long double)inf, (long double)inf)), "fsubl(+inf,+inf) -> NaN");

    /* Infinities / overflow / pole. */
    CHECK(bits_f(cplus_fdiv(1.0, 0.0)) == 0x7f800000u, "fdiv(1,+0) -> +inf");
    CHECK(bits_f(cplus_fdiv(-1.0, 0.0)) == 0xff800000u, "fdiv(-1,+0) -> -inf");
    CHECK(bits_f(cplus_fadd(dmax, dmax)) == 0x7f800000u, "fadd(DBL_MAX,DBL_MAX) -> +inf");
    CHECK(bits_f(cplus_fmul(dmax, 2.0)) == 0x7f800000u, "fmul(DBL_MAX,2) -> +inf");
    CHECK(isinf(cplus_faddl((long double)dmax, (long double)dmax)), "faddl(DBL_MAX,DBL_MAX) -> +inf");
    CHECK(isinf(cplus_fdivl((long double)1.0, (long double)0.0L)), "fdivl(1,+0) -> +inf");

    /* Finite values still round correctly after narrowing. */
    CHECK(bits_f(cplus_fadd(1.0, 0x1p-24)) == 0x3f800000u, "tie-to-even at 1.0");
    CHECK(bits_f(cplus_fmul(1.0, 1.0)) == 0x3f800000u, "fmul(1,1) -> 1");
    CHECK(bits_f(cplus_fdiv(1.0, 1.0)) == 0x3f800000u, "fdiv(1,1) -> 1");
}

static void test_rounding_modes(void) {
    const double one = 1.0;
    const double quarter = 0x1p-25; /* quarter of the binary32 ULP at 1.0 */
    const double half = 0x1p-24;    /* exact binary32 midpoint at 1.0      */
    static const struct {
        int mode;
        uint32_t add_q, sub_q, tie;
    } cases[] = {
        { FE_TONEAREST,  0x3f800000u, 0x3f800000u, 0x3f800000u },
        { FE_UPWARD,     0x3f800001u, 0x3f800000u, 0x3f800001u },
        { FE_DOWNWARD,   0x3f800000u, 0x3f7fffffu, 0x3f800000u },
        { FE_TOWARDZERO, 0x3f800000u, 0x3f7fffffu, 0x3f800000u },
    };
    const int saved = fegetround();
    size_t i;
    for (i = 0; i < sizeof cases / sizeof cases[0]; ++i) {
        fesetround(cases[i].mode);
        CHECK(bits_f(cplus_fadd(one, quarter)) == cases[i].add_q, "round mode: add quarter ULP");
        CHECK(bits_f(cplus_fsub(one, quarter)) == cases[i].sub_q, "round mode: sub quarter ULP");
        CHECK(bits_f(cplus_fadd(one, half)) == cases[i].tie, "round mode: exact tie");
    }
    fesetround(saved);
}

static void test_exceptions(void) {
    feclearexcept(FE_ALL_EXCEPT);
    (void)cplus_fdiv(1.0, 0.0);
    CHECK(fetestexcept(FE_DIVBYZERO) != 0, "fdiv raises FE_DIVBYZERO");

    feclearexcept(FE_ALL_EXCEPT);
    (void)cplus_fadd(INFINITY, -INFINITY);
    CHECK(fetestexcept(FE_INVALID) != 0, "fadd raises FE_INVALID");

    feclearexcept(FE_ALL_EXCEPT);
    (void)cplus_fmul(0.0, INFINITY);
    CHECK(fetestexcept(FE_INVALID) != 0, "fmul raises FE_INVALID");

    feclearexcept(FE_ALL_EXCEPT);
    (void)cplus_fadd(FLT_MAX, FLT_MAX);
    CHECK(fetestexcept(FE_OVERFLOW) != 0, "float overflow raises FE_OVERFLOW");

    feclearexcept(FE_ALL_EXCEPT);
    (void)cplus_fdiv(1.0, 3.0);
    CHECK(fetestexcept(FE_INEXACT) != 0, "inexact result raises FE_INEXACT");

    feclearexcept(FE_ALL_EXCEPT);
}

static void test_logging_parity(void) {
    const double x = 0x1.0000010000001p0;
    const double y = 0x1.fffffffffffffp-1;
    uint32_t off[8], on[8];

    cplus_libc_log_set_enabled(0);
    off[0] = bits_f(cplus_fadd(x, y));
    off[1] = bits_f(cplus_faddl((long double)x, (long double)y));
    off[2] = bits_f(cplus_fsub(x, y));
    off[3] = bits_f(cplus_fsubl((long double)x, (long double)y));
    off[4] = bits_f(cplus_fmul(x, y));
    off[5] = bits_f(cplus_fmull((long double)x, (long double)y));
    off[6] = bits_f(cplus_fdiv(x, y));
    off[7] = bits_f(cplus_fdivl((long double)x, (long double)y));

    cplus_libc_log_set_enabled(1);
    on[0] = bits_f(cplus_fadd(x, y));
    on[1] = bits_f(cplus_faddl((long double)x, (long double)y));
    on[2] = bits_f(cplus_fsub(x, y));
    on[3] = bits_f(cplus_fsubl((long double)x, (long double)y));
    on[4] = bits_f(cplus_fmul(x, y));
    on[5] = bits_f(cplus_fmull((long double)x, (long double)y));
    on[6] = bits_f(cplus_fdiv(x, y));
    on[7] = bits_f(cplus_fdivl((long double)x, (long double)y));
    cplus_libc_log_set_enabled(0);

    CHECK(memcmp(off, on, sizeof off) == 0, "logging ON/OFF result parity");
}

static void report_blocked(void) {
    printf("test_math_c23_farith: SKIP faddf (%s)\n", CPLUS_C23_FARITH_BLOCKER_FADDF);
    printf("test_math_c23_farith: SKIP fsubf (%s)\n", CPLUS_C23_FARITH_BLOCKER_FSUBF);
    printf("test_math_c23_farith: SKIP fmulf (%s)\n", CPLUS_C23_FARITH_BLOCKER_FMULF);
    printf("test_math_c23_farith: SKIP fdivf (%s)\n", CPLUS_C23_FARITH_BLOCKER_FDIVF);
    g_skipped += 4;
}

int main(void) {
    cplus_libc_log_set_enabled(0); /* opt-in logging is OFF by default */

#if CPLUS_C23_FARITH_HAVE_OPERATOR_BACKEND
    test_exact_vectors();
    test_special_values();
    test_rounding_modes();
    test_exceptions();
    test_logging_parity();
#else
    printf("test_math_c23_farith: backend unavailable on this host; all 8 APIs SKIP\n");
    g_skipped += 8;
#endif

    report_blocked();
    printf("test_math_c23_farith: checks=%d failures=%d skipped=%d\n",
           g_checks, g_failures, g_skipped);
    return g_failures != 0;
}
