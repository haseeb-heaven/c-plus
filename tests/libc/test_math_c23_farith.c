/*
 * test_math_c23_farith.c -- standalone C99 tests for the ISO C23
 * fadd/fsub/fmul/fdiv (narrowing) families in math_c23_farith.c.
 *
 * Coverage:
 *   (1) exact-rational oracle: 76 vectors whose expected binary32 bits were
 *       computed with Python Fraction arithmetic and a single correct
 *       round-to-nearest-even (no floating-point shortcut). Includes binary32
 *       midpoints, +/- just-off-midpoint, overflow, subnormal boundaries and
 *       deterministic random cases. Each vector is exercised against both the
 *       double-operand and the long-double-operand wrapper.
 *   (2) explicit IEEE 754 anchors that do not depend on the wrapper: signed
 *       zero, NaN propagation, infinities, overflow and divide-by-zero.
 *   (3) all four C rounding modes on a quarter-ULP and an exact-tie input.
 *   (4) fenv exception flags inherited from the host operators.
 *   (5) logging ON/OFF parity.
 *
 * The four non-C23 names faddf/fsubf/fmulf/fdivf are reported as SKIP with the
 * exact blocker strings from the public header -- no placeholder is asserted.
 *
 * Exact commands and captured output: docs/libc/C23_FARITH_CLOSURE.md.
 */

