static int g_checks = 0;
static int g_failures = 0;
static int g_skipped = 0;

#define CHECK(cond, msg)                                                       \
    do {                                                                       \
        ++g_checks;                                                            \
        if (!(cond)) {                                                         \
            ++g_failures;                                                      \
            fprintf(stderr, "FAIL line %d: %s\n", __LINE__, (msg));            \
        }                                                                      \
    } while (0)

#define FARITH_FADD 0
#define FARITH_FSUB 1
#define FARITH_FMUL 2
#define FARITH_FDIV 3

static double frombits_d(uint64_t u) {
    double d;
    memcpy(&d, &u, sizeof d);
    return d;
}

static uint32_t bits_f(float f) {
    uint32_t u;
    memcpy(&u, &f, sizeof u);
    return u;
}

