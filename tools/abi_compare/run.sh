#!/bin/sh
# run.sh -- ABI fingerprint capture / comparison driver.
#
# Shell + C only (no Python).  It:
#   1. materialises the C probe source into an output directory (this is the
#      "generate a C source" step -- the canonical source lives in this
#      directory and is copied to the build dir each run),
#   2. compiles it with /usr/bin/clang and runs it to capture sizeof/_Alignof/
#      offsetof/enum values plus compile-time function-signature checks,
#   3. captures compiler ABI facts (clang --version, -print-target-triple,
#      ABI-relevant subset of `clang -dM -E`) and exported symbols via nm,
#   4. writes a canonical text fingerprint (fingerprint.txt) and a derived
#      JSON fingerprint (fingerprint.json),
#   5. in compare mode, diffs a freshly generated fingerprint against a
#      committed baseline and exits non-zero on any unexpected difference.
#
# Usage:
#   sh tools/abi_compare/run.sh capture [outdir]
#   sh tools/abi_compare/run.sh baseline
#   sh tools/abi_compare/run.sh compare <baseline.txt> [ignore-file]
#
# Environment overrides:
#   CPLUS_FP_CLANG     (default /usr/bin/clang)
#   CPLUS_FP_NM        (default /usr/bin/nm)
#   CPLUS_FP_DIFF      (default /usr/bin/diff)
#   CPLUS_FP_OUT       (default tools/abi_compare/.out)
#   CPLUS_FP_ARCHIVES  (space-separated archives to symbol-scan)

set -u

SCRIPT_DIR=$(CDPATH= cd -- "$(dirname "$0")" && pwd)
ROOT=$(CDPATH= cd -- "$SCRIPT_DIR/../.." && pwd)
cd "$ROOT" || exit 2

CLANG=${CPLUS_FP_CLANG:-/usr/bin/clang}
NM=${CPLUS_FP_NM:-/usr/bin/nm}
DIFF=${CPLUS_FP_DIFF:-/usr/bin/diff}
OUT=${CPLUS_FP_OUT:-tools/abi_compare/.out}
ARCHIVES=${CPLUS_FP_ARCHIVES:-"build/libc/libcplus_hardened.a build/safe/libcplus_safecrt.a"}

INC="-Ilibc/install-include -Ilibc/include -Ilibc -Istdlib/safe -Ithird_party/safeclib/include -Ithird_party/intel-safestringlib/include"

die() { printf 'abi_fp: %s\n' "$*" >&2; exit 2; }

# ---------------------------------------------------------------------------
# capture_into <dir> : generate C sources, compile, run, write fingerprint.*
# ---------------------------------------------------------------------------
capture_into()
{
    d=$1
    mkdir -p "$d" || die "cannot create output dir $d"

    printf 'abi_fp: generating C sources in %s\n' "$d"
    cp tools/abi_compare/abi_fp_probe.c "$d/abi_fp_probe.c" || die "copy probe failed"
    cp tools/abi_compare/fp_to_json.c   "$d/fp_to_json.c"   || die "copy json helper failed"

    printf 'abi_fp: compile probe   : %s -O2 -std=c11 -Wall -Wextra -Werror <includes> %s/abi_fp_probe.c\n' "$CLANG" "$d"
    # shellcheck disable=SC2086
    $CLANG -O2 -std=c11 -Wall -Wextra -Werror $INC \
        "$d/abi_fp_probe.c" -o "$d/abi_fp_probe" || die "probe compilation failed"

    printf 'abi_fp: compile json    : %s -O2 -std=c11 -Wall -Wextra %s/fp_to_json.c\n' "$CLANG" "$d"
    $CLANG -O2 -std=c11 -Wall -Wextra \
        "$d/fp_to_json.c" -o "$d/fp_to_json" || die "json helper compilation failed"

    {
        printf '# ABI fingerprint (canonical text). Generated by tools/abi_compare/run.sh.\n'
        printf '# Record format: SECTION <TAB> key <TAB> value.\n'
        printf '# Sections: V=meta L=layout C=compiler ABI S=exports/symbols F=function signatures.\n'

        # ---- V: tool/format metadata -------------------------------------
        printf 'V\tformat\tabi_fp_1\n'
        printf 'V\tgenerated_by\ttools/abi_compare/run.sh\n'
        printf 'V\tclang_version\t%s\n' "$($CLANG --version 2>/dev/null | head -n 1)"
        printf 'V\ttarget_triple\t%s\n' "$($CLANG -print-target-triple 2>/dev/null)"

        # ---- L and F: layout + signature probe (compiled C program) ------
        "$d/abi_fp_probe" || die "probe run failed"

        # ---- C: ABI-relevant preprocessor defines ------------------------
        $CLANG -dM -E -x c /dev/null 2>/dev/null \
          | awk '/^#define / && $2 ~ /^(__arm64__|__aarch64__|__x86_64__|__i386__|__LP64__|__ILP32__|__SIZEOF_POINTER__|__SIZEOF_LONG__|__SIZEOF_LONG_LONG__|__SIZEOF_INT__|__SIZEOF_DOUBLE__|__SIZEOF_SIZE_T__|__BYTE_ORDER__|__ORDER_LITTLE_ENDIAN__|__ORDER_BIG_ENDIAN__|__MACH__|__linux__|__ELF__|__APPLE__|__arm__|__ARM_ARCH|__ARM_PCS|__ARM_PCS_AAPCS64|_WIN32|_WIN64|_M_IX86|_M_X64|__STDC__|__STDC_VERSION__|__STDC_HOSTED__|__clang__|__clang_major__|__clang_minor__|__GNUC__|__gnu_linux__|__PIC__|__PIE__|__CHAR_BIT__|__FLT_MANT_DIG__|__DBL_MANT_DIG__)$/ { print "C\tdefine " $2 "\t" $3 }' \
          | sort -u

        # ---- S: exported symbols from built archives ----------------------
        for a in $ARCHIVES; do
            if [ -f "$a" ]; then
                syms=$($NM -gU "$a" 2>/dev/null \
                       | awk '$2 ~ /^[A-Z]$/ && NF >= 3 { print $3 }' \
                       | sort -u)
                count=$(printf '%s\n' "$syms" | awk 'NF { c++ } END { print c+0 }')
                printf 'S\tarchive %s\tcount=%s\n' "$a" "$count"
                printf '%s\n' "$syms" | while IFS= read -r sym; do
                    [ -n "$sym" ] && printf 'S\tsymbol %s::%s\t1\n' "$a" "$sym"
                done
            else
                printf 'S\tarchive %s\tMISSING\n' "$a"
            fi
        done
    } > "$d/fingerprint.txt" || die "fingerprint capture failed"

    "$d/fp_to_json" < "$d/fingerprint.txt" > "$d/fingerprint.json" \
        || die "json generation failed"

    printf 'abi_fp: wrote %s/fingerprint.txt (%s records) and fingerprint.json\n' \
        "$d" "$(awk 'NF && $0 !~ /^#/' "$d/fingerprint.txt" | wc -l | tr -d ' ')"
}

# ---------------------------------------------------------------------------
# filter_records <ignore-file|-> : drop ignored records from stdin.
# Ignore file lines: "SEC" (whole section) or "SEC<TAB>key-prefix".
# ---------------------------------------------------------------------------
filter_records()
{
    ig=$1
    if [ -n "$ig" ] && [ "$ig" != "-" ] && [ -f "$ig" ]; then
        awk -F'\t' -v ign="$ig" '
            FNR == NR {
                if ($0 ~ /^[[:space:]]*$/ || $0 ~ /^#/) next
                ig[++n] = $0
                next
            }
            {
                keep = 1
                for (i = 1; i <= n; ++i) {
                    split(ig[i], a, "\t")
                    if (a[1] == $1 && (a[2] == "" || substr($2, 1, length(a[2])) == a[2])) {
                        keep = 0
                        break
                    }
                }
                if (keep) print
            }
        ' "$ig" -
    else
        cat
    fi
}

# ---------------------------------------------------------------------------
# main
# ---------------------------------------------------------------------------
mode=${1:-capture}

case "$mode" in
    capture)
        outdir=${2:-$OUT}
        capture_into "$outdir" || exit 2
        printf 'abi_fp: capture complete. baseline candidates:\n  %s\n  %s\n' \
            "$outdir/fingerprint.txt" "$outdir/fingerprint.json"
        ;;
    baseline)
        bdir="$ROOT/tests/abi/fingerprints"
        capture_into "$bdir" || exit 2
        mv "$bdir/fingerprint.txt" "$bdir/baseline.txt" || die "baseline move failed"
        mv "$bdir/fingerprint.json" "$bdir/baseline.json" || die "baseline move failed"
        # Leave the baseline directory holding only committed baseline data.
        rm -f "$bdir/abi_fp_probe.c" "$bdir/fp_to_json.c" \
              "$bdir/abi_fp_probe" "$bdir/fp_to_json"
        printf 'abi_fp: refreshed committed baseline:\n  %s\n  %s\n' \
            "$bdir/baseline.txt" "$bdir/baseline.json"
        ;;
    compare)
        baseline=${2:-}
        [ -n "$baseline" ] || die "compare needs a baseline file"
        [ -f "$baseline" ] || die "baseline not found: $baseline"
        ignore=${3:-}
        cmproot="$OUT/compare"
        capture_into "$cmproot" || exit 2

        filter_records "$ignore" < "$baseline"    > "$cmproot/baseline.filtered"
        filter_records "$ignore" < "$cmproot/fingerprint.txt" > "$cmproot/current.filtered"

        if $DIFF -u "$cmproot/baseline.filtered" "$cmproot/current.filtered" \
              > "$cmproot/diff.txt" 2>&1; then
            printf 'abi_fp: ABI fingerprint MATCHES baseline (%s).\n' "$baseline"
            printf 'abi_fp: diff is empty: %s/diff.txt\n' "$cmproot"
            exit 0
        else
            printf 'abi_fp: ABI fingerprint MISMATCH against %s.\n' "$baseline"
            printf 'abi_fp: differences (baseline -> current):\n'
            cat "$cmproot/diff.txt"
            printf 'abi_fp: full diff kept at %s/diff.txt\n' "$cmproot"
            exit 1
        fi
        ;;
    *)
        die "unknown mode '$mode' (use capture or compare)"
        ;;
esac
