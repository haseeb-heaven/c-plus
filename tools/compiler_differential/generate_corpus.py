#!/usr/bin/env python3
"""Write the deterministic differential corpus into tests/compiler/differential.

Regeneration is byte-for-byte reproducible from MASTER_SEED.  The manifest
records each case's seed and source hash so the runner can verify that the
checked-in fixtures still match their seeds before it trusts any result.

Usage:
    python3 tools/compiler_differential/generate_corpus.py
"""

from __future__ import annotations

import json
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
REPO = HERE.parent.parent
DEST = REPO / "tests" / "compiler" / "differential"

sys.path.insert(0, str(HERE))
from corpus import MASTER_SEED, build_corpus  # noqa: E402


def main() -> int:
    cases = build_corpus()
    cases_dir = DEST / "cases"
    cases_dir.mkdir(parents=True, exist_ok=True)

    manifest = {
        "schema": 1,
        "suite": "compiler_differential",
        "master_seed": MASTER_SEED,
        "note": "Generated by tools/compiler_differential/generate_corpus.py; do not edit by hand.",
        "cases": [
            {
                "name": c.name,
                "category": c.category,
                "seed": c.seed,
                "source": "cases/%s.c" % c.name,
                "sha256": c.sha256,
            }
            for c in cases
        ],
    }

    for case in cases:
        (cases_dir / ("%s.c" % case.name)).write_text(case.source, encoding="utf-8")
    (DEST / "manifest.json").write_text(
        json.dumps(manifest, indent=2) + "\n", encoding="utf-8")

    print("wrote %d cases to %s" % (len(cases), cases_dir))
    print("wrote manifest %s" % (DEST / "manifest.json"))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
