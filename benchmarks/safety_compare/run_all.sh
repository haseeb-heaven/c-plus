#!/bin/sh
# benchmarks/safety_compare/run_all.sh
#
# Reproducible driver for every harness in this directory that has an
# executable form:
#   *.c   -> plain C,   /usr/bin/clang -O2                  (build: clang_O2)
#   *.rs  -> Rust,      rustc -O                            (build: rustc_O)
#   *.cp  -> C+ safe,   c+ build --release                  (build: cplus_safe)
#            C+ legacy, c+ build --release --legacy-c       (build: cplus_legacy)
#
# the inspiration language (*.scoped) is intentionally out of scope: this driver covers the
# C+ / Rust / C executable forms only.
#
# Everything generated by this script is written under results/ (binaries,
# build logs, per-run stdout/stderr/exit, the timing helper, table.txt and
# summary.json). No source file is touched.
#
# Environment overrides (all optional):
#   CPLUS_BIN, CPLUS_RUSTC, CPLUS_CLANG,
#   CPLUS_BENCH_RUNS, CPLUS_BENCH_WARMUP,
#   CPLUS_BENCH_RUN_TIMEOUT, CPLUS_BENCH_BUILD_TIMEOUT,
#   CPLUS_BENCH_RESULTS
#
# Exit status: 0 if every required build/run is OK or BLOCKED, 1 if any
# required build/run FAILs. A build that hits the known external C+ runtime
# blocker (CPLUS_EXIT_ARITHMETIC) is reported BLOCKED, not a pass and not a
# required failure, matching the repository's evidence convention.

set -u

ROOT=$(CDPATH= cd -- "$(dirname -- "$0")/../.." && pwd)
HERE="$ROOT/benchmarks/safety_compare"
RESULTS=${CPLUS_BENCH_RESULTS:-"$HERE/results"}
BINDIR="$RESULTS/bin"
LOGDIR="$RESULTS/logs"
RUNDIR="$RESULTS/runs"
RUNNER="$RESULTS/run_one.pl"
SUMMARY="$RESULTS/summary.json"
TABLE="$RESULTS/table.txt"
EVIDENCE_CSV="$RESULTS/evidence.csv"

# Resolve toolchains BEFORE the PATH is pinned.
CPLUS_BIN=${CPLUS_BIN:-"$ROOT/build/c+"}
CPLUS_RUSTC=${CPLUS_RUSTC:-rustc}
case "$CPLUS_BIN" in
  /*) ;;
  *) CPLUS_BIN=$(command -v "$CPLUS_BIN" 2>/dev/null || printf '%s' "$CPLUS_BIN") ;;
esac
case "$CPLUS_RUSTC" in
  /*) ;;
  *) CPLUS_RUSTC=$(command -v "$CPLUS_RUSTC" 2>/dev/null || printf '%s' "$CPLUS_RUSTC") ;;
esac
CLANG=${CPLUS_CLANG:-/usr/bin/clang}

# Fixed environment for every build and every run.
PINNED_PATH=/usr/bin:/bin:/usr/sbin:/sbin:/opt/homebrew/bin
PATH=$PINNED_PATH
export PATH
export LC_ALL=C
export CPLUS_CLANG="$CLANG"   # pin the C+ backend to Apple clang

RUNS=${CPLUS_BENCH_RUNS:-7}
WARMUP=${CPLUS_BENCH_WARMUP:-1}
RUN_TIMEOUT=${CPLUS_BENCH_RUN_TIMEOUT:-30}
BUILD_TIMEOUT=${CPLUS_BENCH_BUILD_TIMEOUT:-300}
PERL=/usr/bin/perl

case "$RUNS" in ''|*[!0-9]*) RUNS=7 ;; esac
case "$WARMUP" in ''|*[!0-9]*) WARMUP=1 ;; esac
case "$RUN_TIMEOUT" in ''|*[!0-9]*) RUN_TIMEOUT=30 ;; esac
case "$BUILD_TIMEOUT" in ''|*[!0-9]*) BUILD_TIMEOUT=300 ;; esac
[ "$RUNS" -ge 1 ] || RUNS=1
[ "$RUN_TIMEOUT" -ge 1 ] || RUN_TIMEOUT=30
[ "$BUILD_TIMEOUT" -ge 1 ] || BUILD_TIMEOUT=300

mkdir -p "$RESULTS" "$BINDIR" "$LOGDIR" "$RUNDIR" || exit 2
# Fresh artifacts for this pass (do not touch unrelated files under results/).
rm -rf "$BINDIR" "$LOGDIR" "$RUNDIR" || exit 2
mkdir -p "$BINDIR" "$LOGDIR" "$RUNDIR" || exit 2

# Bounded-timeout + timing + capture helper. Prints "<elapsed_seconds> <exit>".
cat > "$RUNNER" <<'PERL'
use strict;
use warnings;
use Time::HiRes qw(time);

my ($timeout, $out_file, $err_file, @cmd) = @ARGV;
die "runner: bad arguments\n" unless defined($err_file) && @cmd;
die "runner: bad timeout\n" unless defined($timeout) && $timeout =~ /^\d+$/ && $timeout > 0;

my $t0 = time;
my $pid = fork();
die "runner: fork failed: $!\n" unless defined $pid;
if (!$pid) {
    open(STDOUT, '>', $out_file) or die "runner: open stdout: $!\n";
    open(STDERR, '>', $err_file) or die "runner: open stderr: $!\n";
    exec { $cmd[0] } @cmd or do {
        print STDERR "runner: exec failed: $!\n";
        exit 127;
    };
}

my $timed_out = 0;
eval {
    local $SIG{ALRM} = sub { die "__TIMEOUT__\n" };
    alarm($timeout);
    waitpid($pid, 0);
    alarm(0);
};
if ($@) {
    $timed_out = 1;
    kill 'KILL', $pid;
    waitpid($pid, 0);
}

my $elapsed = time - $t0;
my $raw = $?;
my $code = $timed_out ? 124
         : (($raw & 127) ? 128 + ($raw & 127) : ($raw >> 8));
printf "%.6f %d\n", $elapsed, $code;
PERL

# Execute a command with a hard timeout, capturing stdout/stderr/exit.
timed_exec() {
  _to=$1; _of=$2; _ef=$3; shift 3
  "$PERL" "$RUNNER" "$_to" "$_of" "$_ef" "$@"
}

# Extract the workload checksum from captured stdout. Handles:
#   "19999999900000000"                       (plain integer)
#   "checksum=123 elapsed_s=..."              (key=value)
#   "checksum,a,b,c\n123,1.0,2.0,3.0"         (CSV with header)
extract_checksum() {
  awk -F'[[:space:],=]+' '
    function isnum(x) { return (x ~ /^-?[0-9]+([.][0-9]+)?$/) }
    {
      for (i = 1; i < NF; i++) {
        if ($i == "checksum") {
          if (isnum($(i + 1))) { print $(i + 1); exit }
          next                       # header row, skip it
        }
      }
      if (NF > 0 && isnum($1)) { print $1; exit }
    }
  ' "$1"
}

# Median and linearly-interpolated p95 from a list of sorted samples.
compute_stats() {
  printf '%s\n' $1 | grep -v '^$' | sort -n | awk '
    function pct(p, idx, lo, hi, f) {
      if (n == 0) return 0
      idx = p * (n - 1)
      lo = int(idx) + 1
      hi = lo + 1
      if (hi > n) hi = n
      f = idx - (lo - 1)
      return a[lo] + f * (a[hi] - a[lo])
    }
    { a[NR] = $1 + 0; n = NR }
    END { printf "%.6f %.6f\n", pct(0.5), pct(0.95) }
  '
}

json_escape() {
  printf '%s' "$1" | sed -e 's/\\/\\\\/g' -e 's/"/\\"/g' | tr -d '\n\r'
}

# Parse "<elapsed> <exit>" into ELAPSED_S and RC.
parse_result() {
  case "$1" in
    *" "*) ELAPSED_S=${1% *}; RC=${1##* } ;;
    *) ELAPSED_S=0; RC=125 ;;
  esac
  case "$RC" in ''|*[!0-9]*) RC=125 ;; esac
}

# Build one binary. Sets BUILD_OK, CURRENT_BIN and artifact paths.
build_one() {
  _wl=$1; _lang=$2; _build=$3
  CURRENT_BIN="$BINDIR/${_build}_${_wl}"
  BUILD_OUT="$LOGDIR/${_wl}.${_lang}.${_build}.build.out"
  BUILD_ERR="$LOGDIR/${_wl}.${_lang}.${_build}.build.err"
  BUILD_EXIT_FILE="$LOGDIR/${_wl}.${_lang}.${_build}.build.exit"
  case "$_lang:$_build" in
    c:clang_O2)
      RESULT=$(timed_exec "$BUILD_TIMEOUT" "$BUILD_OUT" "$BUILD_ERR" \
        "$CLANG" -O2 "$HERE/$_wl.c" -o "$CURRENT_BIN") ;;
    rust:rustc_O)
      RESULT=$(timed_exec "$BUILD_TIMEOUT" "$BUILD_OUT" "$BUILD_ERR" \
        "$CPLUS_RUSTC" -O "$HERE/$_wl.rs" -o "$CURRENT_BIN") ;;
    'c+:cplus_safe')
      RESULT=$(timed_exec "$BUILD_TIMEOUT" "$BUILD_OUT" "$BUILD_ERR" \
        "$CPLUS_BIN" build --release "$HERE/$_wl.cp" \
        -I"$ROOT/third_party/yyjson" -L"$ROOT/build/ext" -lyyjson \
        -I"$ROOT" -o "$CURRENT_BIN" $EXTRA_BUILD_ARGS) ;;
    'c+:cplus_legacy')
      RESULT=$(timed_exec "$BUILD_TIMEOUT" "$BUILD_OUT" "$BUILD_ERR" \
        "$CPLUS_BIN" build --release --legacy-c "$HERE/$_wl.cp" \
        -I"$ROOT/third_party/yyjson" -L"$ROOT/build/ext" -lyyjson \
        -I"$ROOT" -o "$CURRENT_BIN" $EXTRA_BUILD_ARGS) ;;
    *)
      RESULT="0.000000 2"
      printf '%s\n' 'unsupported language/build combination' > "$BUILD_ERR" ;;
  esac
  parse_result "$RESULT"
  BUILD_RC=$RC
  printf '%s\n' "$BUILD_RC" > "$BUILD_EXIT_FILE"
  BUILD_ELAPSED_S=$ELAPSED_S
  if [ "$BUILD_RC" -eq 0 ] && [ -x "$CURRENT_BIN" ]; then
    BUILD_OK=1
  else
    BUILD_OK=0
  fi
}

# Run one binary. Sets RUN_OK_COUNT, CHECKSUM, MEDIAN_S, P95_S, STATUS,
# FIRST_OUT/FIRST_ERR/FIRST_EXIT/FIRST_EXIT_VAL.
run_one() {
  _wl=$1; _lang=$2; _build=$3; _tag=$4; _bin=$5
  # optional extra argv for this harness, stored in RUN_ARG
  _args=""
  [ -z "${RUN_ARG:-}" ] || _args=$RUN_ARG

  _wi=1
  while [ "$_wi" -le "$WARMUP" ]; do
    timed_exec "$RUN_TIMEOUT" \
      "$RUNDIR/${_tag}.${_lang}.${_build}.warm.${_wi}.out" \
      "$RUNDIR/${_tag}.${_lang}.${_build}.warm.${_wi}.err" \
      "$_bin" $_args > /dev/null
    _wi=$((_wi + 1))
  done

  _n=0
  CHECKSUM=""
  _samples=""
  _ck_mismatch=0
  RUN_OK_COUNT=0
  while [ "$_n" -lt "$RUNS" ]; do
    _n=$((_n + 1))
    _pad=$(printf '%02d' "$_n")
    FIRST_OUT="$RUNDIR/${_tag}.${_lang}.${_build}.run.${_pad}.out"
    FIRST_ERR="$RUNDIR/${_tag}.${_lang}.${_build}.run.${_pad}.err"
    FIRST_EXIT="$RUNDIR/${_tag}.${_lang}.${_build}.run.${_pad}.exit"
    RESULT=$(timed_exec "$RUN_TIMEOUT" "$FIRST_OUT" "$FIRST_ERR" "$_bin" $_args)
    parse_result "$RESULT"
    printf '%s\n' "$RC" > "$FIRST_EXIT"
    FIRST_EXIT_VAL=$RC
    if [ "$RC" -eq 0 ]; then
      _ck=$(extract_checksum "$FIRST_OUT")
      if [ -z "$CHECKSUM" ]; then
        CHECKSUM=$_ck
      elif [ "$_ck" != "$CHECKSUM" ]; then
        _ck_mismatch=1
      fi
      _samples="$_samples $ELAPSED_S"
      RUN_OK_COUNT=$((RUN_OK_COUNT + 1))
    fi
  done

  MEDIAN_S="-"
  P95_S="-"
  if [ "$RUN_OK_COUNT" -eq "$RUNS" ] && [ "$_ck_mismatch" -eq 0 ]; then
    _stats=$(compute_stats "$_samples")
    MEDIAN_S=${_stats% *}
    P95_S=${_stats##* }
    STATUS=ok
  else
    STATUS=fail
    [ "$_ck_mismatch" -eq 0 ] || CHECKSUM="checksum-mismatch"
  fi
}

# Build + run one (workload, language, build, argv) row, emit table/JSON data.
process() {
  _p_wl=$1; _p_arg=$2; _p_lang=$3; _p_build=$4
  RUN_ARG=$_p_arg

  # Source-specific build quirks. safety_matrix.cp links the checked layers
  # via its own include/lib args, documented in that source file.
  EXTRA_BUILD_ARGS=""
  if [ "$_p_wl" = "safety_matrix" ]; then
    EXTRA_BUILD_ARGS="-- -I. -Istdlib/safe -Ilibc -Ilibc/install-include build/safe/libcplus_safecrt.a build/libc/libcplus_hardened.a"
  fi

  if [ -z "$_p_arg" ]; then
    _p_tag=$_p_wl
    _p_label=$_p_wl
  else
    _p_tag="${_p_wl}_${_p_arg}"
    _p_label="$_p_wl/$_p_arg"
  fi
  # argv may be a path; keep artifact file names flat and filesystem-safe.
  _p_tag=$(printf '%s' "$_p_tag" | tr '/' '_')

  build_one "$_p_wl" "$_p_lang" "$_p_build"
  BUILD_EXIT_VAL=$BUILD_RC

  if [ "$BUILD_OK" -eq 0 ]; then
    BLOCK_REASON=""
    if grep -q 'CPLUS_EXIT_ARITHMETIC' "$BUILD_ERR" 2>/dev/null || \
       grep -q 'failed to compile instrumented C+ runtime' "$BUILD_ERR" 2>/dev/null; then
      STATUS=blocked
      BLOCK_REASON="external C+ runtime blocker: CPLUS_EXIT_ARITHMETIC"
    else
      STATUS=fail
      REQUIRED_FAIL=1
    fi
    RUN_OK_COUNT=0
    CHECKSUM=""
    MEDIAN_S="-"
    P95_S="-"
    FIRST_OUT=""; FIRST_ERR=""; FIRST_EXIT=""; FIRST_EXIT_VAL=""
  else
    BLOCK_REASON=""
    run_one "$_p_wl" "$_p_lang" "$_p_build" "$_p_tag" "$CURRENT_BIN"
    [ "$STATUS" = ok ] || REQUIRED_FAIL=1
  fi

  _run_str="$RUN_OK_COUNT/$RUNS"
  _row=$(printf '%-22s %-6s %-16s %-7s %-20s %10s %10s %-8s' \
    "$_p_label" "$_p_lang" "$_p_build" "$_run_str" \
    "${CHECKSUM:--}" "$MEDIAN_S" "$P95_S" "$STATUS")
  TABLE_ROWS="$TABLE_ROWS$_row
"

  # Feed the C+ evidence validator with our own results (it is last in discovery).
  _csv_med=${MEDIAN_S}; [ "$_csv_med" != "-" ] || _csv_med=0
  _csv_p95=${P95_S}; [ "$_csv_p95" != "-" ] || _csv_p95=0
  EVIDENCE_ROWS="$EVIDENCE_ROWS$_p_label,$_p_lang,$RUNS,$CHECKSUM,$_csv_med,$_csv_p95,$STATUS
"

  _med=${MEDIAN_S}; [ "$_med" != "-" ] || _med=0
  _p95=${P95_S}; [ "$_p95" != "-" ] || _p95=0
  _obj=$(printf '    {"workload":"%s","language":"%s","build":"%s","run_arg":"%s","runs_ok":%s,"runs_total":%s,"checksum":"%s","median_s":%s,"p95_s":%s,"status":"%s","reason":"%s","artifacts":{"build_stdout":"%s","build_stderr":"%s","build_exit":%s,"build_time_s":%s,"run_stdout":"%s","run_stderr":"%s","run_exit":%s}}' \
    "$(json_escape "$_p_label")" \
    "$(json_escape "$_p_lang")" \
    "$(json_escape "$_p_build")" \
    "$(json_escape "$_p_arg")" \
    "$RUN_OK_COUNT" "$RUNS" \
    "$(json_escape "$CHECKSUM")" \
    "$_med" "$_p95" \
    "$STATUS" "$(json_escape "$BLOCK_REASON")" \
    "$(json_escape "$BUILD_OUT")" \
    "$(json_escape "$BUILD_ERR")" \
    "$BUILD_EXIT_VAL" "$BUILD_ELAPSED_S" \
    "$(json_escape "$FIRST_OUT")" \
    "$(json_escape "$FIRST_ERR")" \
    "${FIRST_EXIT_VAL:-0}")
  if [ "$FIRST_JSON" -eq 1 ]; then
    JSON_ROWS=$_obj
    FIRST_JSON=0
  else
    JSON_ROWS="$JSON_ROWS,
$_obj"
  fi
}

# ---------------------------------------------------------------------------
# Discover workloads and run every executable form present.
# ---------------------------------------------------------------------------
WL_LIST=""
for _f in "$HERE"/*.c "$HERE"/*.rs "$HERE"/*.cp; do
  [ -e "$_f" ] || continue
  _b=$(basename "$_f")
  _wl=${_b%.*}
  case " $WL_LIST " in
    *" $_wl "*) ;;
    *) WL_LIST="$WL_LIST $_wl" ;;
  esac
done
WL_LIST=$(printf '%s\n' $WL_LIST | grep -v '^$' | sort)

TABLE_ROWS=""
JSON_ROWS=""
EVIDENCE_ROWS=""
FIRST_JSON=1
REQUIRED_FAIL=0
BLOCKED_COUNT=0
FAILED_COUNT=0
OK_COUNT=0

for wl in $WL_LIST; do
  # A few sources in this directory are tools rather than benchmark loops;
  # give them the argv their own headers document.
  if [ "$wl" = "validate_results" ]; then
    printf 'workload,language,runs,checksum,median,p95,status\n%s' \
      "$EVIDENCE_ROWS" > "$EVIDENCE_CSV"
  fi
  case "$wl" in
    legacy_speed)     ARG_SETS="loop nested" ;;
    safety_matrix)    ARG_SETS="matrix" ;;
    validate_results) ARG_SETS="$EVIDENCE_CSV" ;;
    *)                ARG_SETS="" ;;
  esac
  for arg in $ARG_SETS; do
    if [ -f "$HERE/$wl.c" ]; then
      process "$wl" "$arg" c clang_O2
    fi
  done
  if [ -z "$ARG_SETS" ] && [ -f "$HERE/$wl.c" ]; then
    process "$wl" "" c clang_O2
  fi

  [ -f "$HERE/$wl.rs" ] && process "$wl" "" rust rustc_O

  if [ -f "$HERE/$wl.cp" ]; then
    # Tool-style .cp sources document required argv in their headers.
    case "$wl" in
      safety_matrix)    CP_ARGS="matrix" ;;
      validate_results) CP_ARGS="$EVIDENCE_CSV" ;;
      *)                CP_ARGS="" ;;
    esac
    if [ -n "$CP_ARGS" ]; then
      for arg in $CP_ARGS; do
        process "$wl" "$arg" c+ cplus_safe
        process "$wl" "$arg" c+ cplus_legacy
      done
    else
      process "$wl" "" c+ cplus_safe
      process "$wl" "" c+ cplus_legacy
    fi
  fi
done

# Count statuses from the generated JSON rows (one object per line).
OK_COUNT=$(printf '%s\n' "$JSON_ROWS" | grep -c '"status":"ok"' || true)
BLOCKED_COUNT=$(printf '%s\n' "$JSON_ROWS" | grep -c '"status":"blocked"' || true)
FAILED_COUNT=$(printf '%s\n' "$JSON_ROWS" | grep -c '"status":"fail"' || true)

# Print and persist the requested table.
{
  printf '%-22s %-6s %-16s %-7s %-20s %10s %10s %-8s\n' \
    workload language build run checksum median p95 status
  printf '%-22s %-6s %-16s %-7s %-20s %10s %10s %-8s\n' \
    ---------------------- -------- ---------------- ------- -------------------- ---------- ---------- --------
  printf '%s\n' "$TABLE_ROWS"
} | tee "$TABLE"

CLANG_VER=$("$CLANG" --version 2>/dev/null | sed -n '1p')
RUSTC_VER=$("$CPLUS_RUSTC" --version 2>/dev/null | sed -n '1p')
CPLUS_VER=$("$CPLUS_BIN" --version 2>/dev/null | sed -n '1p')
HOST=$(uname -srm)
STARTED=$(date -u '+%Y-%m-%dT%H:%M:%SZ')

# summary.json -- generated with shell printf only (no Python).
{
  printf '{\n'
  printf '  "generator": "benchmarks/safety_compare/run_all.sh",\n'
  printf '  "generated_at_utc": "%s",\n' "$STARTED"
  printf '  "host": "%s",\n' "$(json_escape "$HOST")"
  printf '  "environment": {\n'
  printf '    "pinned_path": "%s",\n' "$(json_escape "$PINNED_PATH")"
  printf '    "cplus_clang": "%s",\n' "$(json_escape "$CLANG")"
  printf '    "cplus_clang_version": "%s",\n' "$(json_escape "$CLANG_VER")"
  printf '    "cplus_bin": "%s",\n' "$(json_escape "$CPLUS_BIN")"
  printf '    "cplus_version": "%s",\n' "$(json_escape "$CPLUS_VER")"
  printf '    "rustc_bin": "%s",\n' "$(json_escape "$CPLUS_RUSTC")"
  printf '    "rustc_version": "%s",\n' "$(json_escape "$RUSTC_VER")"
  printf '    "lc_all": "C"\n'
  printf '  },\n'
  printf '  "method": {\n'
  printf '    "runs": %s,\n' "$RUNS"
  printf '    "warmup": %s,\n' "$WARMUP"
  printf '    "run_timeout_s": %s,\n' "$RUN_TIMEOUT"
  printf '    "build_timeout_s": %s,\n' "$BUILD_TIMEOUT"
  printf '    "percentiles": "linear interpolation on sorted samples",\n'
  printf '    "checksum": "extracted from captured stdout; must be identical on all timed runs of a binary",\n'
  printf '    "scope": "C+ (.cp), Rust (.rs), C (.c); the inspiration language/Fil-C out of scope",\n'
  printf '    "known_blocker": "C+ safe (--release) builds fail against the external runtime missing CPLUS_EXIT_ARITHMETIC; reported as blocked, never as a pass"\n'
  printf '  },\n'
  printf '  "counts": {"ok": %s, "blocked": %s, "fail": %s},\n' \
    "$OK_COUNT" "$BLOCKED_COUNT" "$FAILED_COUNT"
  printf '  "results": [\n%s\n  ],\n' "$JSON_ROWS"
  printf '  "required_failures": %s,\n' "$REQUIRED_FAIL"
  printf '  "status": "%s"\n' "$([ "$REQUIRED_FAIL" -eq 0 ] && printf PASS || printf FAIL)"
  printf '}\n'
} > "$SUMMARY"

echo
echo "summary: $SUMMARY"
echo "table:   $TABLE"
echo "counts:  ok=$OK_COUNT blocked=$BLOCKED_COUNT fail=$FAILED_COUNT required_failures=$REQUIRED_FAIL"
if [ "$BLOCKED_COUNT" -ne 0 ]; then
  echo "note:    blocked rows are external-toolchain blockers (CPLUS_EXIT_ARITHMETIC), not passes"
fi

if [ "$REQUIRED_FAIL" -ne 0 ]; then
  exit 1
fi
exit 0
